"use strict";

// Круглую зону нельзя было схватить за середину.
//
// Попадание курсором идёт в два прохода: сперва НЕзалитые контуры (клик точно
// по обводке выбирает именно её объект), потом ТЕЛА залитых. Во втором проходе
// проверялось только f.ring — круг туда не попал вовсе. На экране сплошная
// заливка, а клик в середину не выбирал ничего: объект как будто дырявый.
//
// Дуга телом НЕ ловится и не должна: это кривая, а не площадная фигура.

const assert = require("node:assert/strict");
const источник = require("./_source").читатьЧистый("app-input.js");

// ---- проход 2 (тела) обязан знать про круг ----
const проход2 = источник.slice(источник.indexOf("for (const { f } of cand) {",
  источник.indexOf("for (const { f } of cand) {") + 1));
const телоКонец = проход2.indexOf("return null;");
const тела = проход2.slice(0, телоКонец);

assert.match(тела, /f\.ring && \(pointInPolygon\(wx, wy, f\)/,
  "тело кольца проверяется pointInPolygon — опора теста");
assert.match(тела, /f\.circle[\s\S]{0,220}Math\.hypot\(cc\.cx - wx, cc\.cy - wy\) <= cc\.r \+ tolW/,
  "тело круга обязано ловиться во втором проходе, иначе клик в середину не выбирает ничего");
assert.doesNotMatch(тела, /f\.arc/,
  "дуга — кривая, тела у неё нет и во втором проходе ей делать нечего");

// ---- проход 1 (незалитые контуры) не должен перехватывать залитый круг ----
assert.match(источник, /if \(f\.circle && !isFilled\(f\)\) \{/,
  "в первом проходе круг обязан проверяться только когда он НЕ залит — как кольцо");

// ---- featureHitsPoint (список всех объектов под точкой) ----
assert.match(источник, /if \(f\.circle\) return Math\.hypot\(f\.circle\.cx - wx, f\.circle\.cy - wy\) <= f\.circle\.r \+ tolW;/,
  "«все объекты под точкой» тоже обязаны видеть тело круга");
assert.match(источник, /if \(f\.arc\) return Math\.abs\(Math\.hypot\(f\.arc\.cx - wx, f\.arc\.cy - wy\) - f\.arc\.r\) < tolW;/,
  "а дуга там же остаётся проверкой по контуру");

// ---- сама геометрия попадания, на числах ----
const вКруге = (cx, cy, r, x, y, tol) => Math.hypot(cx - x, cy - y) <= r + tol;
assert.equal(вКруге(0, 0, 50, 0, 0, 1), true, "середина круга — попадание");
assert.equal(вКруге(0, 0, 50, 50, 0, 1), true, "точка ровно на обводке — попадание");
assert.equal(вКруге(0, 0, 50, 80, 0, 1), false, "снаружи — мимо");
assert.equal(вКруге(0, 0, 50, 50.5, 0, 1), true, "чуть снаружи, в пределах допуска — попадание");

console.log("circle-hit-body: OK");
