"use strict";

// Окно оформления слоя: раскладка не должна держаться на согласованных числах.
//
// Что было на снимке от человека («всё окно сделано криво»):
//   • переключатель режимов — сетка `grid-template-columns` на ДВЕ колонки при
//     ТРЁХ кнопках. Режим «По диапазонам» добавили, сетку не поправили: третья
//     кнопка уехала во второй ряд и вылезла за шапку на 23px;
//   • шапке выдавали `padding-right:400px` под переключатель шириной 320px —
//     два числа, обязанных совпадать с содержимым; заголовок из-за этого резался
//     на 463px при свободных 978;
//   • «Показывать до масштаба» стояла первой полосой во всю ширину (108px) и
//     первой же получала фокус, пока колонка настроек не влезала вдвое;
//   • полторы сотни строк каталога знаков лежали ниже безусловного `return`.
//
// Сторожим не пиксели (они меняются), а способ: раскладка держится на потоке,
// а не на числах, которые кто-то должен помнить.

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const css = fs.readFileSync(path.join(root, "redesign/layers-studio.css"), "utf8");
const studio = fs.readFileSync(path.join(root, "redesign/layers-studio.js"), "utf8");
const a11y = fs.readFileSync(path.join(root, "redesign/a11y.js"), "utf8");
const ui = fs.readFileSync(path.join(root, "app-style-ui.js"), "utf8");

// ---------- переключатель режимов не считает свои кнопки числом в CSS ----------
{
  const правило = (css.match(/#ls-mode\{[^}]*\}/) || [""])[0];
  assert.ok(правило, "правило #ls-mode обязано существовать");
  assert.doesNotMatch(правило, /grid-template-columns/,
    "число колонок в CSS обязано совпадать с числом кнопок в разметке — " +
    "и однажды не совпало. Раскладку задаёт поток (flex), а не пересчитанное число:\n  " + правило);
  assert.doesNotMatch(правило, /position:absolute/,
    "переключатель, вынутый из потока, требует ручного места в шапке — " +
    "именно эти два числа и разъехались");

  const кнопок = (ui.match(/id="style-mode-\w+"/g) || []).length;
  assert.equal(кнопок, 3, `кнопок режима ${кнопок} — при изменении набора перечитайте это правило`);
}

// ---------- шапка не резервирует место числом ----------
{
  const шапка = (css.match(/\.layer-style-studio \.modal-head\{[^}]*\}/) || [""])[0];
  assert.ok(шапка, "правило шапки обязано существовать");
  const отступ = шапка.match(/padding:[^;}]*/);
  assert.ok(!отступ || !/\b[2-9]\d\d px?\b|\b[2-9]\d\dpx/.test(отступ[0]),
    "трёхзначный отступ в шапке — это зарезервированное место под соседний блок; " +
    "заголовок обрежется, как только сосед изменится:\n  " + шапка);
  assert.match(шапка, /display:flex/,
    "заголовок и переключатель делят строку потоком, а не вычисленными отступами");
}

// ---------- масштабная видимость живёт среди свойств, а не над окном ----------
{
  const панель = ui.slice(ui.indexOf("function styleSingleModePanel"),
    ui.indexOf("function styleRulesModePanel"));
  const сетка = панель.indexOf('<div class="style-editor-grid">');
  const масштаб = панель.indexOf("${scaleSection}");
  assert.ok(масштаб > сетка && сетка > 0,
    "«Показывать до масштаба» — свойство слоя, а не заголовок: над сеткой оно " +
    "занимало полосу во всю ширину и первым перехватывало фокус");
}

// ---------- ничего не переносит базовый знак прочь от предпросмотра ----------
{
  assert.doesNotMatch(studio, /controls\.(prepend|append)\(presetLabel\)/,
    "базовый знак и его предпросмотр смотрят вместе — переносить его в " +
    "прокручиваемую колонку значит разнести причину и следствие по разным концам окна");
}

// ---------- автофокус не садится на то, что меняется от пробела ----------
{
  const начало = a11y.indexOf("const ОПАСНЫЕ");
  assert.ok(начало > 0, "список небезопасных для автофокуса типов обязан существовать");
  const блок = a11y.slice(начало, a11y.indexOf(".focus({ preventScroll: true })", начало));
  for (const тип of ["checkbox", "radio", "range"])
    assert.ok(блок.includes(`[type="${тип}"]`),
      `автофокус обязан пропускать ${тип}: пробел или стрелка на нём сразу правят проект`);
  assert.match(блок, /\$\{ОПАСНЫЕ\}/,
    "список обязан подставляться в селектор автоцели, а не просто лежать рядом");
}

// ---------- недостижимого кода нет ----------
{
  // Полторы сотни строк каталога знаков лежали ниже безусловного `return` в
  // теле функции: не выполнялись ни разу, но исправно грузились и всплывали
  // в поиске по коду, изображая живую возможность.
  const файлы = [...fs.readdirSync(root).filter(f => f.endsWith(".js"))
    .map(f => [f, path.join(root, f)]),
    ...fs.readdirSync(path.join(root, "redesign")).filter(f => f.endsWith(".js"))
      .map(f => ["redesign/" + f, path.join(root, "redesign", f)])];
  const промахи = [];
  for (const [имя, путь] of файлы) {
    const строки = fs.readFileSync(путь, "utf8").split("\n");
    строки.forEach((строка, i) => {
      if (!/^\s*return;\s*$/.test(строка)) return;
      const отступ = строка.match(/^\s*/)[0].length;
      // следующая значащая строка на том же отступе и не закрывает блок
      for (let j = i + 1; j < строки.length; j++) {
        const с = строки[j];
        if (!с.trim() || /^\s*(\/\/|\/\*|\*)/.test(с)) continue;
        const о = с.match(/^\s*/)[0].length;
        if (о < отступ || /^\s*[}\])]/.test(с)) break;
        if (о === отступ) промахи.push(`${имя}:${j + 1}  ${с.trim().slice(0, 60)}`);
        break;
      }
    });
  }
  assert.deepEqual(промахи, [],
    "код ниже безусловного return не выполнится никогда, но грузится и " +
    "выглядит рабочим:\n  " + промахи.join("\n  "));
}

console.log("style-studio-layout: OK");
