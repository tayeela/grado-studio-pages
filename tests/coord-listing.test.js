"use strict";

// Ведомость координат поворотных точек.
//
// Это документ: его подшивают к чертежу и по нему выносят точки в натуру.
// Ошибка в дирекционном угле — это забор, поставленный не туда. Поэтому здесь
// проверяются ЧИСЛА на геометрии, ответ для которой известен заранее.
//
// Дирекционный угол: от направления на СЕВЕР, ПО ЧАСОВОЙ стрелке, 0…360°.
// Это не угол строки ввода «25<90» (там от востока против часовой) — две
// разные величины, и путать их нельзя.

const assert = require("node:assert/strict");
const { directionalAngle, formatDMS, coordListing, coordListingText } =
  require("../app-annotate.js");

const близко = (a, b, ε, что) => assert.ok(Math.abs(a - b) < ε,
  `${что}: ожидалось ${b}, получено ${a}`);

// ---------- четыре стороны света ----------
{
  // координаты холста: [восток, север]
  близко(directionalAngle([0, 0], [0, 10]), 0, 1e-9, "на север — 0°");
  близко(directionalAngle([0, 0], [10, 0]), 90, 1e-9, "на восток — 90°");
  близко(directionalAngle([0, 0], [0, -10]), 180, 1e-9, "на юг — 180°");
  близко(directionalAngle([0, 0], [-10, 0]), 270, 1e-9, "на запад — 270°");
  близко(directionalAngle([0, 0], [10, 10]), 45, 1e-9, "северо-восток — 45°");
  близко(directionalAngle([0, 0], [-10, 10]), 315, 1e-9, "северо-запад — 315°");
  assert.equal(directionalAngle([5, 5], [5, 5]), 0, "нулевая сторона не ломает счёт");
}

// ---------- градусы, минуты, секунды ----------
{
  assert.equal(formatDMS(0), `0°00'00"`, "ноль");
  assert.equal(formatDMS(90), `90°00'00"`, "прямой угол");
  assert.equal(formatDMS(45.5), `45°30'00"`, "половина градуса — тридцать минут");
  assert.equal(formatDMS(1.0125), `1°00'45"`, "секунды");
  // округление секунд не должно давать «60»
  assert.equal(formatDMS(1 - 1e-9), `1°00'00"`, "почти градус округляется в градус");
}

// ---------- ведомость квадрата ----------
{
  // Квадрат 100×100, обход против часовой на холсте: восток → север → запад → юг.
  const квадрат = [[0, 0], [100, 0], [100, 100], [0, 100]];
  const строки = coordListing(квадрат, {});
  assert.equal(строки.length, 4, "четыре точки — четыре строки");

  // X это север, Y это восток — проверяем, что не переставлены
  assert.deepEqual([строки[1].X, строки[1].Y], [0, 100],
    "вторая точка: север 0, восток 100");

  for (const р of строки) близко(р.длина, 100, 1e-9, "все стороны по сто метров");
  близко(строки[0].дирекционный, 90, 1e-9, "первая сторона — на восток");
  близко(строки[1].дирекционный, 0, 1e-9, "вторая — на север");
  близко(строки[2].дирекционный, 270, 1e-9, "третья — на запад");
  близко(строки[3].дирекционный, 180, 1e-9, "замыкающая — на юг");
}

// ---------- ломаная: у последней точки стороны нет ----------
{
  const строки = coordListing([[0, 0], [0, 50], [30, 50]], { line: true });
  assert.equal(строки.length, 3);
  близко(строки[0].длина, 50, 1e-9, "первая сторона");
  assert.equal(строки[2].длина, null, "у конца ломаной стороны нет");
  assert.equal(строки[2].дирекционный, null, "и угла нет");
}

// ---------- нумерация с приставкой, как в межевых планах ----------
{
  const строки = coordListing([[0, 0], [1, 0], [1, 1]], { prefix: "н" });
  assert.deepEqual(строки.map(р => р.номер), ["н1", "н2", "н3"], "н1, н2, н3");
}

// ---------- текст вставляется в Word и Excel таблицей ----------
{
  const текст = coordListingText(coordListing([[0, 0], [100, 0], [100, 100], [0, 100]], {}));
  const строки = текст.split("\n");
  assert.equal(строки.length, 5, "шапка и четыре строки");
  assert.match(строки[0], /X \(север\), м\tY \(восток\), м/,
    "шапка называет, где север, а где восток");
  assert.equal(строки[1].split("\t").length, 5, "пять столбцов, разделены табуляцией");
  assert.match(строки[1], /90°00'00"/, "дирекционный угол в градусах и минутах");
}

console.log("coord-listing: OK");
