"use strict";

// Разбор каталога координат.
//
// Каталог приходит вставкой из ГПЗУ, межевого плана, Word или Excel — и каждый
// раз выглядит иначе. Проверяем не «не падает ли», а ЧИСЛА: площадь контура
// обязана совпасть с той, что стоит в документе.

const assert = require("node:assert/strict");
const { parseCoordTable, coordTableSummary } = require("../app-input-line.js");

const близко = (a, b, ε, что) => assert.ok(Math.abs(a - b) < ε,
  `${что}: ожидалось ${b}, получено ${a}`);

// ---------- десятичная запятая не разваливает число ----------
{
  // Ловушка, на которую я сам наступил: если считать запятую разделителем
  // столбцов, «7401,22» превращается в 7401 и 22, и в контур уходит точка,
  // которой в документе нет. Молча и с правдоподобным видом.
  const { точки } = parseCoordTable("1\t7401,22\t12489,10", {});
  assert.equal(точки.length, 1, "одна строка — одна точка");
  близко(точки[0][0], 12489.10, 1e-9, "восток из Y с запятой");
  близко(точки[0][1], 7401.22, 1e-9, "север из X с запятой");
}

// ---------- геодезический порядок по умолчанию ----------
{
  // В каталогах МСК первым столбцом идёт X — это СЕВЕР.
  const { точки } = parseCoordTable("1 100 500", {});
  assert.deepEqual(точки[0], [500, 100], "X=100 север → y холста, Y=500 восток → x");

  const мат = parseCoordTable("1 100 500", { order: "math" });
  assert.deepEqual(мат.точки[0], [100, 500], "математический порядок — как есть");
}

// ---------- номер точки не попадает в координаты ----------
{
  const { точки } = parseCoordTable("т12 7383.45 12456.78", {});
  assert.deepEqual(точки[0], [12456.78, 7383.45], "берутся два ПОСЛЕДНИХ числа");
  const безНомера = parseCoordTable("7383.45 12456.78", {});
  assert.deepEqual(безНомера.точки[0], [12456.78, 7383.45], "без номера тоже верно");
}

// ---------- шапка и подписи не молчат ----------
{
  const текст = ["№ X Y", "1 100 200", "2 300 400", "Всего 2 точки"].join("\n");
  const { точки, пропущено } = parseCoordTable(текст, {});
  assert.equal(точки.length, 2, "разобраны обе строки с числами");
  assert.deepEqual(пропущено, ["№ X Y", "Всего 2 точки"],
    "непонятые строки возвращаются человеку, а не теряются молча");
}

// ---------- площадь совпадает с документом ----------
{
  // Квадрат 100 × 100 по каталогу: площадь ровно 10 000 м², периметр 400 м.
  const квадрат = ["1 0 0", "2 0 100", "3 100 100", "4 100 0", "5 0 0"].join("\n");
  const { точки } = parseCoordTable(квадрат, {});
  const с = coordTableSummary(точки);
  assert.equal(с.точек, 5, "пять строк — пять точек, включая замыкающую");
  assert.equal(с.замкнут, true, "последняя точка совпала с первой");
  близко(с.площадь, 10000, 1e-6, "площадь квадрата");
  близко(с.периметр, 400, 1e-6, "периметр с замыкающей стороной");
}

// ---------- незамкнутый контур виден по зазору ----------
{
  const почти = ["1 0 0", "2 0 100", "3 100 100", "4 100 0", "5 0 0.5"].join("\n");
  const с = coordTableSummary(parseCoordTable(почти, {}).точки);
  assert.equal(с.замкнут, false, "полметра — это не замыкание");
  близко(с.зазор, 0.5, 1e-6, "зазор показан числом, чтобы решал человек");
}

// ---------- пустое и мусор ----------
{
  assert.deepEqual(parseCoordTable("", {}).точки, [], "пустая вставка — ноль точек");
  assert.deepEqual(parseCoordTable("совсем не таблица", {}).точки, [],
    "текст без чисел не превращается в геометрию");
  const одно = parseCoordTable("1 42", {});
  assert.equal(одно.точки.length, 1, "«1 42» это пара чисел — точка");
}

console.log("coord-table: OK");
