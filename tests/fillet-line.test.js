"use strict";

// Скругление всех углов линии разом делало линию ДЛИННЕЕ и рисовало её
// поверх самой себя.
//
// Каждый угол считался по исходным точкам и брал от прилегающих рёбер полный
// подрез d = r/tan(a/2). У двух соседних углов ребро между ними одно, и оба
// брали от него по d. На ломаной [0,0]-[30,0]-[30,10]-[60,10] радиусом 8
// ребро длиной 10 отдавало 8 первому углу (дуга кончалась в [30,8]) и 8
// второму (его дуга начиналась в [30,2]): линия шла вверх, откатывалась на
// 6 м вниз по тому же отрезку и снова шла вверх. Длина 70 м превращалась в
// 75.06 м вместо укорачивания.
//
// Проверяем не числа вчерашнего дня, а само свойство: скругление углов
// СРЕЗАЕТ угол, значит длина обязана падать, а ход вдоль общего ребра —
// не менять знак.

const assert = require("node:assert/strict");
const vm = require("node:vm");

const source = require("./app-source");
const start = source.indexOf("function filletLine(");
const end = source.indexOf("function filletCornerAt(", start);
assert.ok(start >= 0 && end > start,
  "filletLine и cornerArcPoints обязаны оставаться извлекаемыми для этой проверки");

const context = vm.createContext({ Math, Number });
vm.runInContext(source.slice(start, end), context);
const { filletLine, cornerArcPoints } = context;

const длина = pts => {
  let s = 0;
  for (let i = 1; i < pts.length; i++) s += Math.hypot(pts[i][0] - pts[i-1][0], pts[i][1] - pts[i-1][1]);
  return s;
};

// ---------- срезанный угол короче острого ----------
{
  const ломаная = [[0, 0], [30, 0], [30, 10], [60, 10]];
  const исх = длина(ломаная);
  for (const r of [1, 3, 5, 8, 20, 100]) {
    const got = filletLine(ломаная, r);
    assert.ok(длина(got) <= исх + 1e-9,
      `R=${r}: после скругления ${длина(got).toFixed(2)} м вместо ${исх} м — ` +
      "срез угла не может удлинять линию, значит она пошла назад по себе");
    // сравниваем через JSON: массивы приходят из другого realm (vm), и
    // deepStrictEqual разошёлся бы на прототипах, а не на числах
    assert.equal(JSON.stringify(got[0]), "[0,0]", `R=${r}: начало линии обязано остаться на месте`);
    assert.equal(JSON.stringify(got[got.length - 1]), "[60,10]", `R=${r}: конец линии обязан остаться на месте`);
  }
}

// ---------- ход вдоль общего ребра не разворачивается ----------
{
  // ребро [30,0]-[30,10] общее у двух углов: по нему движение только вверх
  const got = filletLine([[0, 0], [30, 0], [30, 10], [60, 10]], 8);
  const наРебре = got.filter(p => Math.abs(p[0] - 30) < 1e-9);
  for (let i = 1; i < наРебре.length; i++)
    assert.ok(наРебре[i][1] >= наРебре[i-1][1] - 1e-9,
      `на общем ребре точка ${JSON.stringify(наРебре[i])} ниже предыдущей ` +
      `${JSON.stringify(наРебре[i-1])} — линия откатилась назад по себе`);
}

// ---------- подрезы двух соседей помещаются в общее ребро ----------
{
  // прямые углы: d = r, значит при r=8 на ребре 10 два соседа обязаны ужаться
  const got = filletLine([[0, 0], [30, 0], [30, 10], [60, 10]], 8);
  const внизу = got.filter(p => Math.abs(p[0] - 30) < 1e-9)[0];
  const вверху = got.filter(p => Math.abs(p[0] - 30) < 1e-9).pop();
  assert.ok(внизу[1] <= вверху[1],
    "касательные точки соседних дуг обязаны идти по порядку, а не внахлёст");
}

// ---------- одиночный угол не ужимается зря ----------
{
  // единственный угол на длинных рёбрах: делить ребро не с кем, радиус полный
  const arc = cornerArcPoints([0, 0], [100, 0], [100, 100], 10);
  const q1 = arc[0], q2 = arc[arc.length - 1];
  assert.ok(Math.abs(q1[0] - 90) < 1e-6 && Math.abs(q1[1]) < 1e-6,
    `подрез одиночного угла ${JSON.stringify(q1)} вместо [90,0] — радиус ужали без причины`);
  assert.ok(Math.abs(q2[0] - 100) < 1e-6 && Math.abs(q2[1] - 10) < 1e-6,
    `вторая касательная ${JSON.stringify(q2)} вместо [100,10]`);
}

// ---------- вырожденное входит и выходит целым ----------
{
  assert.equal(JSON.stringify(filletLine([[0, 0], [10, 0]], 5)), "[[0,0],[10,0]]",
    "двум точкам скруглять нечего");
  assert.equal(JSON.stringify(filletLine([[0, 0], [5, 0], [10, 0]], 5)), "[[0,0],[5,0],[10,0]]",
    "прямой участок обязан остаться прямым, а не потерять вершину");
  const совпали = [[0, 0], [0, 0], [10, 0], [10, 10]];
  assert.equal(filletLine(совпали, 3).length >= 4, true, "нулевое ребро не должно ронять точки");
}

console.log("fillet-line: OK");
