"use strict";

// Исходник холста целиком. app.js разрезан на четырнадцать частей; порядок
// файлов здесь — тот же, что в index.html, и тот же, каким был порядок строк
// прежнего единого app.js.
//
// Тесты ищут код по тексту исходника. Если бы каждый читал только app.js,
// разрез ослабил бы их МОЛЧА: искомое уехало бы в соседний файл, поиск
// перестал бы что-либо находить, а тест остался бы зелёным. Поэтому чтение
// идёт единственным путём — через этот модуль.

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");

const PARTS = require("./app-source-parts");

// экспортируем строку: тесты пользуются ею как прежним содержимым app.js
module.exports = PARTS.map(name => fs.readFileSync(path.join(root, name), "utf8")).join("\n");
