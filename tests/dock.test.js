"use strict";

// Рабочая панель (док).
//
// Окна, в которых работают ГЛЯДЯ НА ЧЕРТЁЖ, были модальными. Замер: «Оформление
// слоя» закрывало 84% холста, «Варианты» 46%, «Таблица атрибутов» 31%, и во всех
// трёх клик по холсту не проходил — его ловил оверлей. Окно мешало ровно тому,
// ради чего открыто.
//
// Док ставит такое окно РЯДОМ с холстом: холст ужимается (замер: 761 → 560 при
// окне 1400) и остаётся видимым и кликабельным, буфер canvas пересчитывается.
//
// Главное в решении — окна НЕ переписываются: переезжает сам оверлей, а его
// кнопки и обработчики продолжают работать. Тест стережёт именно это свойство,
// потому что от него зависит цена перевода следующих окон.

const assert = require("node:assert/strict");
const { читать, читатьЧистый } = require("./_source");

const html = читать("index.html");
// Код — без комментариев: детектор ищет в тексте ровно то, что комментарии и
// объясняют, и уже трижды за сессию ловил собственное объяснение.
const dock = читатьЧистый("redesign/dock.js");
const shell = читатьЧистый("redesign/shell.css");
const styleUi = читатьЧистый("app-style-ui.js");

// ---------- док есть в разметке и подключён ----------
assert.match(html, /<aside id="dock"[^>]*hidden/,
  "док обязан быть в разметке и по умолчанию скрыт");
assert.match(html, /redesign\/dock\.js\?v=/, "dock.js обязан быть подключён с версией");
assert.match(html, /class="dock-body"/, "тело дока — место, куда переезжает оверлей");

// ---------- док стоит РЯДОМ с холстом, а не поверх ----------
{
  const правило = (shell.match(/#dock\{[^}]*\}/) || [""])[0];
  assert.ok(правило, "правило #dock обязано существовать");
  assert.doesNotMatch(правило, /position:\s*(fixed|absolute)/,
    "док, вынутый из потока, снова накроет холст — весь смысл в том, что он его ужимает");
  assert.match(правило, /flex:0 0 auto/, "док — элемент раскладки рядом с холстом");

  const докированный = (shell.match(/\.modal-overlay\.docked\{[^}]*\}/) || [""])[0];
  assert.match(докированный, /position:static/,
    "докированный оверлей перестаёт быть оверлеем");
  assert.match(докированный, /background:none/,
    "затемнение в доке недопустимо: оно и делало холст недоступным");
}

// ---------- окно переезжает целиком, а не переписывается ----------
{
  assert.match(dock, /body\.replaceChildren\(overlay\)/,
    "в док переезжает САМ оверлей — иначе каждое следующее окно придётся переписывать");
  assert.match(dock, /new MutationObserver/,
    "закрытие ловим наблюдателем: окно закрывают его собственные кнопки через overlay.remove()");
}

// ---------- крестик дока не крадёт откат ----------
assert.match(dock, /querySelector\("#ls-cancel[^"]*"\)/,
  "крестик дока обязан нажимать РОДНУЮ кнопку отмены окна: со своим крестиком " +
  "правки оформления остались бы применёнными вопреки «Отмене»");

// ---------- док не зависит от кадров ----------
assert.doesNotMatch(dock, /requestAnimationFrame/,
  "в фоновой вкладке requestAnimationFrame не идёт вовсе (замер: 0 кадров за 400 мс). " +
  "Пересчёт холста делает ResizeObserver на самом canvas — своего сигнала доку не нужно.");

// ---------- док и панель свойств не делят экран ----------
assert.match(shell, /body\.dock-open #panel[^{]*\{display:none\}/,
  "вместе они съедают холст: замер на окне 1400 дал 241px чертежа из 761");

// ---------- окна «работы по чертежу» переведены ----------
{
  // Список закрыт намеренно: сюда попадает окно, в котором ЧТО-ТО ищут или
  // сверяют на самом чертеже. Подтверждения, мастера и справка остаются
  // модальными — их незачем держать рядом с холстом.
  const ПЕРЕВЕДЕНЫ = [
    ["app-style-ui.js", "оформление слоя", "закрывало 84% холста"],
    ["app-attr.js", "таблица атрибутов", "строку выбирают, чтобы найти объект на чертеже"],
    ["app-layer-ui.js", "варианты", "сравнивают, глядя на посадку"],
    ["app-data.js", "данные по области", "область задают по холсту"],
  ];
  for (const [файл, имя, зачем] of ПЕРЕВЕДЕНЫ)
    assert.match(читатьЧистый(файл), /window\.dockOverlay\?\.\(overlay/,
      `«${имя}» обязано открываться в доке: ${зачем}`);
}

// ---------- ширина окна в доке не остаётся модальной ----------
{
  // У окон есть собственные правила ширины ТОЙ ЖЕ специфичности в файле,
  // который грузится позже (.modal.data-modal.data-wizard = width:1080px).
  // Без id в селекторе окно оставалось шириной 1058px внутри дока в 560.
  assert.match(shell, /#dock \.modal-overlay\.docked>\.modal\{[^}]*width:100%/,
    "правило ширины докированного окна обязано перебивать собственные правила окон");
}

console.log("dock: OK");
