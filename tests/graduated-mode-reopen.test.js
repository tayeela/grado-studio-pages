"use strict";

// Оформление по диапазонам исчезало от одного открытия окна.
//
// Режим «По диапазонам» сохраняет ДВА следа: настройки расчёта в
// layer.fmt.graduated и сами классы в layer.rules — правилами-диапазонами
// (field/min/max/patch, без value и style_id). Режим окна определялся по
// наличию rules: «есть правила — значит по значению поля». Слой, оформленный
// по диапазонам, открывался во вкладке «По значению поля», где его классы
// выглядят пустыми строками. Достаточно было нажать «Применить»: фильтр
// непустых правил (field && value !== "" && style_id) не пропускал ни одного
// диапазона, и обработчик стирал и rules, и fmt.graduated. Раскраска по полю
// пропадала, а человек не делал ничего, кроме как заглянул в окно.
//
// Сохранённые настройки расчёта важнее наличия правил. Явную просьбу
// вызывающего (opts.mode) при этом не трогаем: «Оформление по значению поля»
// из меню обязано открывать свою вкладку.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const src = читатьЧистый("app-style-ui.js");

assert.match(src, /let mode = opts\.mode \|\| \(origRules && origRules\.length \? "rules" : "single"\);/,
  "исходное определение режима обязано остаться находимым");
assert.match(src, /if \(!opts\.mode && gradSaved\.field\) mode = "graduated";/,
  "сохранённые настройки диапазонов обязаны выигрывать у наличия rules — " +
  "иначе окно открывается не в той вкладке и стирает классы при «Применить»");
assert.ok(!/if \(mode !== "rules" && gradSaved\.field\)/.test(src),
  "прежнее условие пропускало ровно тот случай, ради которого писалось: " +
  "у слоя с диапазонами rules ВСЕГДА непусты");

// сохранение по-прежнему пишет оба следа — иначе восстанавливать будет нечего
{
  const тело = src.slice(src.indexOf('} else if (mode === "graduated") {'));
  assert.match(тело.slice(0, 400), /layer\.rules = град\.rules\(\);/, "классы");
  assert.match(тело.slice(0, 400), /layer\.fmt\.graduated = gradSettings\(\);/, "настройки расчёта");
}

// просьба вызывающего остаётся сильнее сохранённых настроек
assert.match(src, /opts\.mode \|\|/, "явно запрошенный режим обязан открываться как есть");

console.log("graduated-mode-reopen: OK");
