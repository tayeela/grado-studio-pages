"use strict";

// Естественные границы (Jenks) сверены с эталонным ckmeans из
// simple-statistics: та же задача, тот же минимизируемый показатель — сумма
// внутриклассовых квадратов отклонений (SDCM). Замеры до правки, k = 5:
//
//   площадь, тяжёлый хвост, 50 000 значений — хуже эталона на 17 %
//   две группы, 50 000 значений             — хуже на 64 %
//   почти одно значение и редкие выбросы    — хуже в 37 раз
//
// Три причины, все молчаливые:
//
// 1. Выборка прореживалась до 1200 значений «потому что на границах классов
//    это не сказывается». Сказывалось: в городской выгрузке тысячи участков
//    одинаковой застройки и десяток особых, после прореживания особых в
//    выборке остаются единицы и границы встают не туда.
// 2. Совпавшие границы схлопывались все подряд, включая ПОСЛЕДНЮЮ. Верхний
//    класс замкнут с обеих сторон, поэтому при равных границах он не пуст:
//    на наборе …,50,51,52,100 метод верно выделял 100 в отдельный класс, а
//    до карты доезжало три класса вместо четырёх — выброс слипался с 50–52.
// 3. Границы округлялись до тысячных. Верхняя уходила ВНИЗ от настоящего
//    максимума (940.7352 → 940.735), и самый крупный объект не попадал ни в
//    один класс: `parsed <= rule.max` для него ложь. Замер — по одному-два
//    объекта без класса на дробных данных, и всегда среди них самый крупный.
//
// Сторож проверяет не «те же числа, что вчера», а СВОЙСТВА: совпадение с
// эталонными SDCM, полноту разбиения и то, что прореживание не вернулось.

const assert = require("node:assert/strict");
const path = require("node:path");
const { читатьЧистый } = require("./_source");

global.window = global;
require(path.join(__dirname, "..", "app-symbology.js"));
const S = global.GRADO_SYMBOLOGY;
assert.ok(S && typeof S.classify === "function", "модуль символики обязан подниматься без документа");

// повторяемый генератор: сторож не имеет права мигать
let seed = 42;
const rnd = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
const норм = () => { let s = 0; for (let i = 0; i < 6; i++) s += rnd(); return s - 3; };
const набор = (n, ген) => Array.from({ length: n }, ген).sort((a, b) => a - b);

function sdcm(values, breaks) {
  let total = 0;
  for (let k = 0; k < breaks.length - 1; k++) {
    const низ = breaks[k], верх = breaks[k + 1], последний = k === breaks.length - 2;
    const группа = values.filter(v => v >= низ && (последний ? v <= верх : v < верх));
    if (!группа.length) continue;
    const среднее = группа.reduce((a, b) => a + b, 0) / группа.length;
    for (const v of группа) total += (v - среднее) ** 2;
  }
  return total;
}

// Эталон — ответы ckmeans@simple-statistics 7.8.8 на этих же наборах при
// k = 5. Числа вписаны сюда, чтобы сторож не тянул зависимость.
const НАБОРЫ = [
  ["этажность (лог-норм)", 5000, () => Math.max(1, Math.round(Math.exp(1.4 + 0.55 * норм()))), 9.553e2],
  ["площадь (тяжёлый хвост)", 5000, () => Math.round(Math.exp(6 + 1.5 * норм())), 3.410e8],
  ["две группы", 5000, (_, i) => (i % 2 ? 10 + 3 * норм() : 90 + 6 * норм()), 1.195e4],
  ["равномерно", 5000, () => rnd() * 1000, 1.700e7],
];

for (const [имя, n, ген, эталон] of НАБОРЫ) {
  seed = 42;
  const values = набор(n, (_, i) => ген(_, i));
  const breaks = S.classify(values, { method: "jenks", classes: 5 });
  const наш = sdcm(values, breaks);
  assert.ok(наш <= эталон * 1.02,
    `${имя}: разброс внутри классов ${наш.toExponential(3)}, у эталонного ckmeans ` +
    `${эталон.toExponential(3)} — разбивка хуже оптимальной`);
}

// ---------- разбиение полное: ни один объект не остаётся без класса ----------
{
  const случаи = [
    ["дробные с выбросами", набор(500, (_, i) => (i % 200 === 0 ? 500 + rnd() * 500 : 10 + rnd()))],
    ["целые", набор(2000, () => Math.max(1, Math.round(Math.exp(1.4 + 0.55 * норм()))))],
    ["крупные дробные", набор(2000, () => Math.exp(6 + 1.5 * норм()))],
  ];
  for (const [имя, values] of случаи) {
    const { rules } = S.buildGraduated(values.map((v, i) => ({ id: i, props: { p: v } })),
      { field: "p", method: "jenks", classes: 5 });
    const попало = v => rules.filter(rule => S.ruleMatchesValue(rule, v)).length;
    for (const v of [values[0], values[values.length - 1]])
      assert.equal(попало(v), 1, `${имя}: крайнее значение ${v} попало в ${попало(v)} классов вместо одного`);
    const без = values.filter(v => попало(v) === 0).length;
    assert.equal(без, 0, `${имя}: ${без} объектов не попали ни в один класс — на карте они без цвета`);
    const дважды = values.filter(v => попало(v) > 1).length;
    assert.equal(дважды, 0, `${имя}: ${дважды} объектов попали сразу в два класса`);
  }
}

// ---------- одинокий максимум остаётся отдельным классом ----------
{
  const values = [1, 1, 1, 2, 2, 2, 3, 3, 10, 11, 12, 50, 51, 52, 100];
  const breaks = S.classify(values, { method: "jenks", classes: 4 });
  assert.equal(breaks.length, 5,
    `выброс 100 обязан остаться отдельным классом, границы: ${JSON.stringify(breaks)}`);
  assert.deepEqual(breaks, [1, 10, 50, 100, 100],
    "ckmeans на этом наборе даёт группы [1..3], [10..12], [50..52], [100]");
}

// ---------- прореживание не вернулось ----------
{
  const источник = читатьЧистый("app-symbology.js");
  const тело = источник.slice(источник.indexOf("function jenks"));
  const конец = тело.slice(0, тело.indexOf("\n  }") + 4);
  assert.doesNotMatch(конец, /MAX\s*=\s*\d+/,
    "прореживание выборки возвращает молчаливую ошибку на выбросах: считаем целиком");
  assert.match(конец, /Float64Array/,
    "стоимость отрезка обязана браться из префиксных сумм, иначе точный счёт не успеет");
}

// ---------- 50 000 значений считаются, а не подвисают ----------
{
  seed = 7;
  const values = набор(50000, () => Math.exp(6 + 1.5 * норм()));
  const начало = process.hrtime.bigint();
  const breaks = S.classify(values, { method: "jenks", classes: 7 });
  const мс = Number(process.hrtime.bigint() - начало) / 1e6;
  assert.equal(breaks.length, 8, "семь классов — восемь границ");
  // замер: 26 мс при O(k·n·log n); потолок с запасом — ловим возврат к O(n²·k)
  assert.ok(мс < 600, `50 000 значений считались ${мс.toFixed(0)} мс — сложность снова квадратичная?`);
}

console.log("jenks-vs-ckmeans: OK");
