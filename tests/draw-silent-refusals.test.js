"use strict";

// Инструменты черчения отказывали МОЛЧА: человек тянет рамку или ставит три
// точки, а на холсте ничего — и ни слова почему.
//
// Прямоугольник: порог протяжки меряется в пикселях (4 px), а сторона — в
// метрах (1 м). На крупном масштабе, где метр больше четырёх пикселей, между
// порогами щель: протяжка засчитана, прямоугольник не создан, сообщения нет.
// Плюс непригодный активный слой (линейный, точечный) отбрасывал прямоугольник
// так же молча.
//
// Дуга: три коллинеарные точки давали null и молчание. Хуже — проверка на
// коллинеарность абсолютная (|c| < 1e-6), а c растёт как КВАДРАТ размера
// чертежа. Три почти коллинеарные точки на сотне метров проверку проходят и
// дают дугу радиусом в миллиарды метров: на экране это прямая, но её габарит
// уходит в пространственный индекс и в «показать всё».

const assert = require("node:assert/strict");
const vm = require("node:vm");
const { читатьЧистый } = require("./_source");

// ---------- вырожденная дуга не строится ----------
{
  const src = читатьЧистый("app-geom-edit.js");
  const start = src.indexOf("function arcFrom3Pts");
  const end = src.indexOf("\n}", start) + 2;
  const context = vm.createContext({ Math, isFinite, Number });
  vm.runInContext(src.slice(start, end), context);
  const { arcFrom3Pts } = context;

  assert.equal(arcFrom3Pts([0, 0], [100, 0], [200, 0]), null, "точно прямая — дуги нет");

  // почти прямая: середина отклонена на микрон на стометровой хорде
  const почти = arcFrom3Pts([0, 0], [100, 1e-6], [200, 0]);
  assert.equal(почти, null,
    "радиус такой «дуги» — миллиарды метров; попав в объекты, она растягивает " +
    "габарит проекта и ломает «показать всё» и поиск по области");

  // настоящая дуга городского размера обязана строиться
  const дуга = arcFrom3Pts([0, 0], [50, 20], [100, 0]);
  assert.ok(дуга && дуга.r > 0 && дуга.r < 1e3, `дуга по трём точкам обязана строиться, получено ${JSON.stringify(дуга)}`);
  assert.ok(Math.abs(Math.hypot(дуга.cx - 0, дуга.cy - 0) - дуга.r) < 1e-6, "центр равноудалён от концов");
  assert.ok(Math.abs(Math.hypot(дуга.cx - 100, дуга.cy - 0) - дуга.r) < 1e-6);

  // большой, но правдоподобный радиус (плавный поворот дороги: 1 м стрелки на
  // километр хорды — это 125 км) запрещать нельзя
  const плавная = arcFrom3Pts([0, 0], [500, 1], [1000, 0]);
  assert.ok(плавная && плавная.r > 1e5 && плавная.r < 1e6,
    `плавная дуга обязана строиться, получено ${JSON.stringify(плавная)}`);
}

// ---------- отказы вслух ----------
{
  const src = читатьЧистый("app-geom-edit.js");
  const тело = src.slice(src.indexOf("function finishDrawing"), src.indexOf("// ---------- разрезать"));
  for (const [что, признак] of [
    ["дуга", /arcFrom3Pts[\s\S]{0,200}?toast\(/],
    ["окружность", /r > 0\.5[\s\S]{0,200}?toast\(/],
  ]) assert.match(тело, признак, `${что}: отказ обязан быть со словами, а не молча`);
}

{
  const src = читатьЧистый("app-input.js");
  // ветка прямоугольника есть и в pointermove, и в pointerup — нужна вторая
  const тело = src.slice(src.lastIndexOf("if (state.drag && state.drag.rect)"));
  const кусок = тело.slice(0, тело.indexOf("} else if (state.drawing"));
  assert.equal((кусок.match(/toast\(/g) || []).length, 2,
    "прямоугольник обязан объяснять оба отказа: слишком мелкий и непригодный слой");
  assert.match(кусок, /geometry_type === "polygon"[\s\S]{0,200}else toast\(/,
    "неполигональный активный слой — отказ со словами");
}

