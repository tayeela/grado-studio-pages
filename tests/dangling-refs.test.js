"use strict";

// Две ссылки, которые никто не проверяет и которые рвутся молча.
//
// 1. <use href="#знак"> в спрайте. Переименовали символ — иконка просто не
//    рисуется: ни ошибки в консоли, ни пустого места в разметке.
// 2. var(--токен) без запасного значения. Необъявленный токен делает всё
//    правило недействительным — это уже случалось, и правка выглядела как
//    «стиль не применился».
//
// Оба случая — одна беда: строковая ссылка, которую компилятор не видит.
// Отдельного линтера ради этого ставить незачем, правило умещается в тест.

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const впапке = (dir, суффикс) => fs.readdirSync(path.join(ROOT, dir))
  .filter(name => суффикс.test(name))
  .map(name => (dir === "." ? name : `${dir}/${name}`));
const читать = отн => fs.readFileSync(path.join(ROOT, отн), "utf8");

const исходники = [...впапке(".", /\.(js|html|css)$/), ...впапке("redesign", /\.(js|css)$/)];

// ---------- 1. знаки спрайта ----------
{
  const html = читать("index.html");
  const символы = new Set([...html.matchAll(/<symbol[^>]*\bid="([^"]+)"/g)].map(m => m[1]));
  assert.ok(символы.size > 40, `символов в спрайте всего ${символы.size} — сломался разбор`);

  const битые = [];
  for (const файл of исходники)
    for (const m of читать(файл).matchAll(/href="#([a-zA-Z0-9_-]+)"/g))
      if (!символы.has(m[1])) битые.push(`${m[1]} ← ${файл}`);
  assert.deepEqual(битые, [],
    "ссылки на знаки, которых нет в спрайте (иконка не нарисуется молча):\n  " + битые.join("\n  "));
}

// ---------- 2. токены оформления ----------
{
  const объявлены = new Set();
  const использованы = [];
  for (const файл of исходники) {
    const текст = читать(файл);
    for (const m of текст.matchAll(/(^|[;{\s])(--[a-zA-Z0-9_-]+)\s*:/g)) объявлены.add(m[2]);
    // токен может заводиться и из кода — element.style.setProperty("--x", …)
    for (const m of текст.matchAll(/setProperty\(\s*["'](--[a-zA-Z0-9_-]+)["']/g)) объявлены.add(m[1]);
    // var(--x, запасное) не в счёт: запасное значение и есть защита от пропажи
    for (const m of текст.matchAll(/var\(\s*(--[a-zA-Z0-9_-]+)\s*\)/g)) использованы.push([m[1], файл]);
  }
  assert.ok(объявлены.size > 50, `объявленных токенов всего ${объявлены.size} — сломался разбор`);

  const битые = использованы.filter(([имя]) => !объявлены.has(имя))
    .map(([имя, файл]) => `${имя} ← ${файл}`);
  assert.deepEqual([...new Set(битые)], [],
    "var() на необъявленный токен убивает ВСЁ правило, а не одно свойство:\n  " + битые.join("\n  "));
}

console.log("dangling-refs: OK");
