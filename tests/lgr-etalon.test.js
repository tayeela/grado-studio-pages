// Знаки ЛГР против эталонных QML Москвы.
//
// Знаки правились по одному, глядя на экран, — сутки работы, и часть всё равно
// осталась неверной. Здесь вся библиотека сверяется с эталоном разом.
//
// Эталон: tools/lgr-reference/*.qml (выгрузка стилей QGIS), снятый в
// etalon.json через `python tools/lgr_diff.py --snapshot`. Сам QML лежит рядом,
// так что снимок в любой момент воспроизводится из первоисточника.
//
// ЕДИНИЦЫ — здесь ошибиться легче всего, поэтому правило живёт прямо тут.
// QML: MM — миллиметры бумаги, MapUnit — метры местности, Pixel — пиксель
// устройства (зумом не масштабируется; у нас на него «читаемый режим», сверять
// нечего). Наша библиотека при ground_units хранит размеры в ПИКСЕЛЯХ ХОЛСТА НА
// ОПОРНОМ МАСШТАБЕ — так их читает groundFactor в app-labels-place.js:
//     px = метры × MM_PX / (ref_scale / 1000)
// При ref_scale 2000: 1 м = 3.7795 / 2 = 1.88975 px, отсюда 6 м = 11.34.
// Первая версия сверялки приняла эти px за метры и объявила 37 знаков
// сломанными ровно на 1.88975. Знаки были верны — врала сверялка.

const fs = require("fs");
const path = require("path");

const КОРЕНЬ = path.join(__dirname, "..");
const MM_PX = 96 / 25.4;

const эталон = JSON.parse(
  fs.readFileSync(path.join(КОРЕНЬ, "tools", "lgr-reference", "etalon.json"), "utf8"));

const текст = fs.readFileSync(path.join(КОРЕНЬ, "styles-lib.js"), "utf8");
const библиотека = JSON.parse(
  текст.slice(текст.indexOf("{", текст.indexOf("=")), текст.lastIndexOf("}") + 1));

const поКоду = new Map();
for (const [id, знак] of Object.entries(библиотека))
  if (знак.lgr_code != null && !поКоду.has(знак.lgr_code)) поКоду.set(знак.lgr_code, [id, знак]);

// метры местности / миллиметры бумаги → пиксели холста
function вПиксели(значение, ед, знак) {
  if (ед === "MapUnit") return значение * MM_PX / ((знак.ref_scale || 2000) / 1000);
  if (ед === "MM") return значение * MM_PX;
  return null;                       // Pixel — не сверяем
}

// Осознанные отступления от QML. Не «знак сломан», а решение заказчика; список
// короткий и с причиной, иначе он превратится в свалку, куда сметают неудобные
// находки. Сторож продолжает следить за ВСЕМИ остальными признаками знака.
const ОТСТУПЛЕНИЯ = {
  47: { поля: ["цвет", "засечки", "штрих"],
        почему: "ООЗТ по решению заказчика чертится знаком ООПТ (код 8), " +
                "а не собственной зелёной линией из QML 2022 года" },
};

const беды = [];
for (const [код, э] of Object.entries(эталон)) {
  const пара = поКоду.get(Number(код));
  if (!пара) { беды.push(`[${код}] ${э.label}: нет в библиотеке`); continue; }
  const [id, знак] = пара;
  const где = `[${код}] ${э.label} (${id})`;
  const отступление = ОТСТУПЛЕНИЯ[код] || { поля: [] };
  const сверяем = поле => !отступление.поля.includes(поле);

  if (сверяем("цвет") && э.цвет && знак.stroke && э.цвет.toLowerCase() !== знак.stroke.toLowerCase())
    беды.push(`${где}: цвет эталон ${э.цвет}, у нас ${знак.stroke}`);

  if (э.ширина) {
    const ждём = вПиксели(э.ширина.v, э.ширина.ед, знак);
    if (ждём != null && Math.abs((знак.width || 0) - ждём) > 0.3)
      беды.push(`${где}: ширина эталон ${ждём.toFixed(2)} px, у нас ${(знак.width || 0).toFixed(2)}`);
  }

  const ждётШтрих = !!э.штрих || !э.сплошная;
  if (!сверяем("штрих")) { /* отступление: штрих знака взят у другого кода */ } else {
  const нашШтрих = !!(знак.dash && знак.dash.length);
  if (ждётШтрих !== нашШтрих) {
    беды.push(`${где}: ${ждётШтрих ? "должен быть штрих, у нас сплошная"
                                   : "должна быть сплошная, у нас штрих"}`);
  } else if (э.штрих && нашШтрих) {
    const ждём = э.штрих.v.map(v => вПиксели(v, э.штрих.ед, знак));
    const разошлись = ждём.length !== знак.dash.length ||
      ждём.some((v, i) => v == null || Math.abs(v - знак.dash[i]) > 0.3);
    if (разошлись)
      беды.push(`${где}: штрих эталон [${ждём.map(v => v == null ? "?" : v.toFixed(2))}], ` +
                `у нас [${знак.dash.map(v => v.toFixed(2))}]`);
  }
  }

  const ждёмЗасечки = э.маркеров > 0;
  if (!сверяем("засечки")) { /* отступление: засечки знака взяты у другого кода */ }
  else if (ждёмЗасечки !== !!знак.line_marker) {
    беды.push(`${где}: засечки ${ждёмЗасечки ? "есть в эталоне, у нас нет"
                                             : "нет в эталоне, у нас есть"}`);
  } else if (ждёмЗасечки) {
    // QGIS рисует засечки в обе стороны двумя MarkerLine с углами 0 и 180 —
    // отсюда «в обе» в снимке. Форму и заливку не сверяем: наш словарь
    // (tick/tee/corner/chevron) в SimpleMarker QGIS один-в-один не переводится.
    const вОбе = знак.line_marker.dir === "both";
    if (э.засечка_в_обе !== вОбе)
      беды.push(`${где}: засечки ${э.засечка_в_обе ? "в эталоне в обе стороны, у нас в одну"
                                                   : "в эталоне в одну сторону, у нас в обе"}`);
  }
}

if (беды.length) {
  console.error(`знаки ЛГР разошлись с эталоном (${беды.length}):`);
  for (const b of беды) console.error("  •", b);
  process.exit(1);
}
const оговорки = Object.entries(ОТСТУПЛЕНИЯ)
  .map(([код, о]) => `[${код}] ${о.поля.join(", ")} — ${о.почему}`);
console.log(`ok: ${Object.keys(эталон).length} знаков ЛГР совпадают с эталонными QML` +
  (оговорки.length ? `, кроме оговорённого:\n  • ${оговорки.join("\n  • ")}` : ""));
