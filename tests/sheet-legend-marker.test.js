"use strict";

// Легенда листа («условные обозначения» в печатной колонке, app-sheet.js)
// печатала знак с засечкой/треугольником ГОЛОЙ чертой: drawSample вообще не
// читал style.line_marker. Тот же знак на самом чертеже засечку несёт —
// читающий лист видел не тот условный знак, что на плане.
//
// Живой замер в браузере (drawSheetColumn → drawSample на реальном холсте,
// стиль {stroke:"#d91a1a", line_marker:{shape:"triangle",...}}) поймал ДВА
// самостоятельных дефекта по ходу починки:
//
//  1. drawMarkerGlyph рисует в РАЗДЕЛЯЕМЫЙ модульный ctx (см. app-render.js),
//     а не в переданный drawSample аргумент context — эти два имени в общем
//     случае разные объекты (сравните с app-dxf.js, который уже подменяет ctx
//     ради переиспользования той же функции). Без подмены маркер рисовался бы
//     не на тот холст либо не рисовался вовсе.
//  2. drawMarkerGlyph красит ТЕКУЩИМ ctx.fillStyle/strokeStyle, а не своим
//     аргументом — без явной установки маркер брал ЧУЖОЙ цвет, оставшийся от
//     ПРЕДЫДУЩЕЙ отрисовки (заголовок «Условные обозначения» тёмно-серым
//     текстом рисуется прямо перед этим). Живой пиксельный замер поймал
//     это буквально: цвет заливки оказался (68,66,60) — не (217,26,26),
//     как у самого знака.
//
// Направление — по требованию: маркер в условном обозначении СМОТРИТ ВВЕРХ,
// не вниз (симметрично для одиночного ряда, как у остальных условных —
// _markerGlyphsSVG в app.js, свотчи слоёв и библиотеки стилей). У drawSample
// нет полигона, значит нет и «внутрь»/«наружу»: направление одно и то же,
// какой бы ни была настройка dir у самого знака.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const src = читатьЧистый("app-sheet.js");
const start = src.indexOf("function drawSample(");
const end = src.indexOf("function tepRows(");
assert.ok(start > 0 && end > start, "drawSample обязана оставаться извлекаемой");
const тело = src.slice(start, end);

// ---------- маркер читается вообще ----------
assert.match(тело, /if \(style\.line_marker && style\.line_marker\.shape\) \{/,
  "образец полилинии обязан проверять line_marker — иначе знак с засечкой " +
  "печатается в легенде голой чертой");

// ---------- ctx подменяется на переданный context, как у DXF-экспорта ----------
assert.match(тело, /const savedCtx = ctx;\s*\n\s*ctx = context;/,
  "drawMarkerGlyph пишет в разделяемый модульный ctx, не в свой аргумент — " +
  "без подмены знак либо рисуется не туда, либо не рисуется вовсе " +
  "(см. тот же приём в app-dxf.js)");
assert.match(тело, /\} finally \{ ctx = savedCtx; \}/,
  "ctx обязан вернуться к прежнему значению — иначе следующая обычная " +
  "отрисовка сцены пишет в подмену");

// ---------- цвет маркера — цвет ЭТОГО знака, а не унаследованный от прежней отрисовки ----------
assert.match(тело, /ctx\.fillStyle = ctx\.strokeStyle = style\.stroke \|\| "#5c5a54";/,
  "заливку и обводку маркера обязано ставить явно ДО вызова drawMarkerGlyph — " +
  "тот красит текущим состоянием ctx, а не аргументом; без явной установки " +
  "маркер наследует цвет предыдущей отрисовки (замерено: тёмно-серый текст " +
  "заголовка вместо цвета знака)");
{
  const цветИдёт = тело.indexOf("ctx.fillStyle = ctx.strokeStyle");
  const рисуем = тело.indexOf("drawMarkerGlyph(mk,");
  assert.ok(цветИдёт > 0 && цветИдёт < рисуем, "цвет обязан ставиться ДО вызова, а не после");
}

// ---------- маркер смотрит вверх: nx=0, ny=+1 ----------
// Проверено пиксельно вживую: при этих nx/ny у drawMarkerGlyph основание
// треугольника уходит ВНИЗ (positive ny — в канве это вниз), а остриё
// остаётся на линии — то есть острая вершина ВЫШЕ основания, треугольник
// смотрит вверх. Тот же результат у _markerGlyphsSVG (одиночный ряд — ny=+1).
assert.match(тело, /drawMarkerGlyph\(mk, x \+ width \/ 2, midY, 1, 0, 0, 1, s, width\);/,
  "маркер обязан смотреть вверх (nx=0, ny=+1) — тот же выбор, что и у всех " +
  "остальных условных (_markerGlyphsSVG), не вниз");

console.log("sheet-legend-marker: OK");
