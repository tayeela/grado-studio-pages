"use strict";

// Один и тот же вопрос — «каким знаком нарисован слой» — задавался двумя
// разными способами, и половина мест отвечала неверно.
//
// layerStyle(L) отдаёт только знак, записанный НА СЛОЕ (style_id + fmt). У
// слоёв ГИС ОГД знак живёт на ОБЪЕКТАХ: он выбирается по коду ЛГР при
// импорте и лежит в f.style_id, а на слое не записан вовсе. Легенда листа и
// панель слоёв это учитывали и смотрели на образцовый объект, а вот три
// места спрашивали layerStyle напрямую и получали пустоту:
//
//   окно «Оформление слоя» — серый #888888 вместо красного, и «Применить
//     стиль» покрасило бы весь слой в этот серый;
//   выгрузка QML — слой уезжал в QGIS БЕЗ ОФОРМЛЕНИЯ;
//   таблица слоёв в DXF — цвет 7 и CONTINUOUS у всех подряд, то есть объект,
//     переведённый в AutoCAD на «ПоСлою», белел и терял штрих.
//
// Замеры после правки на слое «Красные линии УДС» со знаком lgr.kl.top:
// layerStyle даёт {}, layerShownStyle — stroke #fe0004, штрих [11.34, 3.78],
// подпись «кл топ»; в QML едет line_color 254,0,4,255; в таблице слоёв DXF
// строка «Красные_линии_УДС_(КЛ_УДС) … 62 1 … 6 GRADO_D1» вместо 62 7 и
// CONTINUOUS.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

// ---------- общий помощник существует и берёт знак с объекта ----------
{
  const app = читатьЧистый("app.js");
  const начало = app.indexOf("function layerShownStyle");
  assert.ok(начало > 0, "общий ответ на вопрос «чем нарисован слой» обязан быть один");
  const тело = app.slice(начало, app.indexOf("\n}", начало) + 2);
  assert.match(тело, /state\.features\.find\(f => layerOf\(f\) === L && !f\.fmt\)/,
    "образец берётся без личной правки объекта, иначе за весь слой отвечает один объект");
  assert.match(тело, /образец \? styleOf\(образец\) : \(layerStyle\(L\) \|\| \{\}\)/,
    "есть объекты — знак с объекта, нет объектов — знак слоя");
}

// ---------- места, где ответ идёт наружу, спрашивают именно его ----------
{
  const случаи = [
    ["app-export.js", /layerToQml\(layer, layerShownStyle\(layer\)/,
      "иначе слой уезжает в QGIS без оформления"],
    ["app-dxf.js", /layerShownStyle === "function" \? layerShownStyle\(layer\)/,
      "иначе таблица слоёв в DXF уходит с цветом 7 и CONTINUOUS у всех подряд"],
    ["app-shell.js", /const st = layerShownStyle\(L\);/,
      "чип «куда я черчу» обязан быть цвета слоя, а не серым"],
  ];
  for (const [файл, шаблон, зачем] of случаи)
    assert.match(читатьЧистый(файл), шаблон, `${файл}: ${зачем}`);
}

// ---------- прежний способ туда вернуться не должен ----------
{
  for (const файл of ["app-export.js", "app-dxf.js"]) {
    const src = читатьЧистый(файл);
    assert.doesNotMatch(src, /layerStyle\(layer\)/,
      `${файл}: знак слоя напрямую снова спрашивать нельзя — у слоёв ГИС ОГД он пуст`);
  }
}

// ---------- места, где layerStyle уместен, не тронуты ----------
{
  // база для градуированных правил — это именно оформление СЛОЯ, поверх
  // которого кладётся патч класса; знак объекта тут не при чём
  assert.match(читатьЧистый("app.js"), /const base = layerStyle\(L\) \|\| \{\};/,
    "у градуированной символики базой остаётся знак слоя");
}

console.log("layer-shown-style: OK");
