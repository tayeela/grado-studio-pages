"use strict";

// Палитра градуированной символики врала о различиях в данных.
//
// Классы отличаются на карте прежде всего СВЕТЛОТОЙ: цветовой тон человек
// сравнивает плохо, а «светлее/темнее» — хорошо. Значит шаг светлоты между
// соседними классами должен быть примерно одинаков. У «Серого» он был 8 и 10
// единиц L* между первыми тремя классами и 28 и 34 между последними: три
// класса из пяти сливались в один серый. Данные различались, карта — нет.
//
// Причина: ступени собрали из подряд идущих значений 9-классовой схемы
// ColorBrewer вместо готовой 5-классовой. Замер до правки — разброс шага
// (max/min): «Серый» 4.2×, «Белый → синий» 2.1×.
//
// Сторож меряет светлоту, а не сверяет список хексов: замена палитры на
// другую хорошую не должна его ронять, а замена на плохую — должна.
// Расходящиеся схемы (светлая середина, тёмные концы) распознаются по смене
// знака шага и проверяются по половинам отдельно.

const assert = require("node:assert/strict");
const path = require("node:path");

global.window = global;
require(path.join(__dirname, "..", "app-symbology.js"));
const SYMBOLOGY = global.SYMBOLOGY || global.GRADO_SYMBOLOGY;
assert.ok(SYMBOLOGY && SYMBOLOGY.RAMPS, "модуль символики обязан подниматься без документа");

// L* из CIELAB: воспринимаемая светлота, а не среднее каналов sRGB
const светлота = hex => {
  const clean = String(hex).replace("#", "");
  const канал = i => parseInt(clean.slice(i, i + 2), 16) / 255;
  const лин = c => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
  const [r, g, b] = [0, 2, 4].map(i => лин(канал(i)));
  const Y = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  return Y > 0.008856 ? 116 * Math.cbrt(Y) - 16 : 903.3 * Y;
};

const РАЗБРОС = 2.5;                    // во сколько раз самый широкий шаг может превышать самый узкий

function проверить(имя, цвета, пометка) {
  const шаги = цвета.slice(1).map((цвет, i) => светлота(цвета[i]) - светлота(цвет));
  const части = [];
  // расходящаяся схема идёт светлее-темнее: рвём её по смене знака и меряем
  // каждую половину отдельно — иначе ровная схема выглядела бы кривой
  let текущая = [шаги[0]];
  for (let i = 1; i < шаги.length; i++) {
    if (Math.sign(шаги[i]) !== Math.sign(шаги[i - 1])) { части.push(текущая); текущая = []; }
    текущая.push(шаги[i]);
  }
  части.push(текущая);
  for (const часть of части) {
    if (часть.length < 2) continue;
    const модули = часть.map(Math.abs);
    const мин = Math.min(...модули), макс = Math.max(...модули);
    assert.ok(мин > 1,
      `${имя} ${пометка}: соседние классы почти не отличаются светлотой (шаг ${мин.toFixed(1)} L*)`);
    assert.ok(макс / мин <= РАЗБРОС,
      `${имя} ${пометка}: шаг светлоты гуляет в ${(макс / мин).toFixed(1)} раза ` +
      `(${модули.map(v => v.toFixed(1)).join(", ")} L*) — часть классов на карте сольётся`);
  }
}

for (const [имя, схема] of Object.entries(SYMBOLOGY.RAMPS)) {
  assert.ok(Array.isArray(схема.stops) && схема.stops.length >= 3,
    `${имя}: у палитры обязаны быть ступени`);
  проверить(имя, схема.stops, "ступени");
  // столько классов, сколько ступеней — цвета берутся напрямую;
  // семь — включается смешивание, и оно тоже обязано остаться ровным
  проверить(имя, SYMBOLOGY.rampColors(имя, 7), "7 классов");
}

console.log("ramp-lightness: OK");
