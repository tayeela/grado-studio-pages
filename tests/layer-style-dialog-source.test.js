"use strict";

// «Оформление слоя» показывало не тот знак, которым слой нарисован.
//
// Жалоба с натуры: открываем оформление слоя «Красные линии УДС» — на холсте
// они красные, а в окне цвет #888888 и предпросмотр серый. Галочка «Подпись
// линии» при этом не делает ничего.
//
// Причина одна на обе беды. Окно брало знак из layerStyle(layer), то есть
// только со СЛОЯ (style_id + fmt). У слоёв ГИС ОГД знак живёт на ОБЪЕКТАХ:
// он выбирается по коду ЛГР при импорте и лежит в f.style_id. Для таких
// слоёв layerStyle возвращает пустой объект — отсюда и запасной серый
// #888888 в поле цвета, и пустая подпись, из-за которой галочка молча не
// срабатывала (подпись берётся из знака, а знака в руках у окна не было).
//
// Хуже того, «Применить стиль» из такого окна покрасило бы весь слой в этот
// серый: человек думает, что правит красные линии, а сохраняет серые.
//
// Вторая половина — необратимость. Выключение хранится в правке слоя
// (line_label: null), и если «исходную подпись» брать из уже применённой
// правки, включать обратно нечего. Поэтому «что показывать» и «что вернуть
// при включении» — РАЗНЫЕ величины: галочка смотрит на текущий знак,
// значение для возврата берётся из исходного знака объекта.
//
// Замеры после правки: окно открывается с #fe0004 (столько же на холсте),
// галочка включена; снять → подпись null и галочка снята; включить →
// подпись «кл топ» вернулась и галочка стоит. Обычный слой со знаком НА СЛОЕ
// не затронут: #b89e59 в окне против #b89e59 в библиотеке.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const src = читатьЧистый("app-style-ui.js");
const начало = src.indexOf("function стильДляОкна");
assert.ok(начало > 0, "источник знака для окна обязан оставаться находимым");
const помощник = src.slice(начало, src.indexOf("function openLayerStyle"));

// ---------- знак берётся с объекта, а не только со слоя ----------
assert.match(помощник, /cur: styleOf\(образец\)/,
  "окно обязано показывать знак, которым слой НАРИСОВАН: у слоёв ГИС ОГД он на объектах");
assert.match(помощник, /state\.features\.find\(f => layerOf\(f\) === layer && !f\.fmt\)/,
  "образец выбирается без личной правки объекта, иначе в окно слоя попадёт оформление ОДНОГО объекта");
assert.match(помощник, /образец\.style_id[\s\S]{0,200}gpZoneSid[\s\S]{0,120}layerSignSid/,
  "знак объекта ищется в том же порядке, что и при отрисовке");

// ---------- значение для возврата — из исходного знака ----------
assert.match(src, /baseLabel = cur\.line_label \|\| знакОбразца\.line_label \|\| null/,
  "включать обратно нечего, если «исходную подпись» брать из уже применённой правки слоя");
assert.match(src, /baseMarker = cur\.line_marker \|\| знакОбразца\.line_marker \|\| null/,
  "та же необратимость была у засечек");

// ---------- а состояние галочек — из текущего знака ----------
{
  const разметка = src.slice(src.indexOf("function styleSingleModePanel"));
  const тело = разметка.slice(0, разметка.indexOf("\n}"));
  assert.match(тело, /id="fmt-label" \$\{cur\.line_label \? "checked" : ""\}/,
    "галочка обязана показывать ТЕКУЩЕЕ состояние: с запасным значением она " +
    "всегда стояла бы включённой, даже когда подпись выключена");
  assert.match(тело, /id="fmt-marker"[^>]*\$\{cur\.line_marker \? "checked" : ""\}/,
    "то же для засечек");
  assert.doesNotMatch(тело, /id="fmt-label" \$\{baseLabel/,
    "baseLabel — это значение для ВОЗВРАТА, а не состояние переключателя");
}

console.log("layer-style-dialog-source: OK");
