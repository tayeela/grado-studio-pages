"use strict";

// Порядок загрузки модуля российских СК.
//
// app-crs-ru.js стоял в index.html НИЖЕ app-shell.js. Скрипты с defer
// выполняются в порядке объявления, а восстановление проекта идёт как раз из
// app-shell.js — значит в момент applyProjectCrs модуля ещё не существовало.
// projectCrsConverters не находил GRADO_CRS_RU, молча возвращал null, и вместо
// МСК Москвы работала встроенная локальная система.
//
// Цена ошибки: весь чертёж в 11 км от места. Проверено эталоном pyproj —
// участок 77:01:0002003:3639 («ул. Большая Полянка, вл. 30») по МГГТ лежит на
// X 7548.35 / Y 7530.87, объекты в проекте там и стояли, а пересчёт координат
// давал 241.72 / −594.60. По кадастровым номерам, адресам и атрибутам всё
// выглядело правильным — расхождение видно только в координатах.

const assert = require("node:assert/strict");
const { читать } = require("./_source");

const html = читать("index.html");

const позиция = имя => {
  const m = new RegExp(`src="\\./${имя}\\.js\\?v=`).exec(html);
  assert.ok(m, `${имя}.js обязан быть подключён`);
  return m.index;
};

// ---------- модуль СК грузится раньше всех, кто применяет систему ----------
{
  // app-geodesy.js: projectCrsConverters читает window.GRADO_CRS_RU
  // app-shell.js:   applyRestoredState применяет СК при открытии проекта
  for (const потребитель of ["app-geodesy", "app-shell"])
    assert.ok(позиция("app-crs-ru") < позиция(потребитель),
      `app-crs-ru.js обязан грузиться ДО ${потребитель}.js: иначе система координат ` +
      `проекта не применится, а чертёж уедет на километры — молча, ` +
      `с правильными кадастровыми номерами и адресами`);
}

// ---------- отсутствие модуля больше не проходит незамеченным ----------
{
  const geodesy = читать("app-geodesy.js");
  const начало = geodesy.indexOf("function projectCrsConverters");
  const блок = geodesy.slice(начало, начало + 900);
  assert.match(блок, /!R \|\| !Array\.isArray\(R\.KNOWN\)/,
    "отсутствие модуля СК обязано проверяться явно");
  assert.match(блок, /console\.error/,
    "и попадать в консоль: молчаливый null подменяет систему координат");
  assert.match(блок, /toast\(/,
    "и доходить до человека: сам он расхождение в координатах не заметит");
}

// ---------- параметры МСК Москвы совпадают с МГГТ (ГОСТ Р 51794-2008) ----------
{
  const ru = читать("app-crs-ru.js");
  const начало = ru.indexOf('id: "msk-moscow"');
  assert.ok(начало > 0, "определение МСК Москвы обязано существовать");
  const блок = ru.slice(начало, начало + 400);
  // Эталон: +proj=tmerc +lat_0=55.66666666667 +lon_0=37.5 +k=1 +x_0=16.098
  //         +y_0=14.512 +ellps=bessel
  //         +towgs84=316.151,78.924,589.650,-1.57273,2.69209,2.34693,8.4507
  for (const [что, шаблон] of [
    ["эллипсоид Бесселя", /ELLIPSOIDS\.bessel/],
    ["осевой меридиан 37.5", /lon0:\s*37\.5\b/],
    ["широта начала 55.6667", /lat0:\s*55\.66666666667/],
    ["масштаб 1", /k:\s*1\b/],
    ["сдвиг X 16.098", /x0:\s*16\.098/],
    ["сдвиг Y 14.512", /y0:\s*14\.512/],
    ["towgs84 по ГОСТ", /316\.151,\s*78\.924,\s*589\.65,\s*-1\.57273,\s*2\.69209,\s*2\.34693,\s*8\.4507/],
  ]) assert.match(блок, шаблон, `МСК Москвы: ${что} обязан совпадать с МГГТ`);
}

console.log("crs-load-order: OK");
