"use strict";

// Окно оформления затирало у знака то, чем не умеет управлять.
//
// В окне нет поля цвета штриховки, густота выбирается из трёх шагов, а у
// засечки правятся только форма, шаг, размер и сторона. Сборка же собирала эти
// объекты С НУЛЯ по значениям полей — и всё остальное, что было у знака,
// исчезало при первом же касании окна:
//   • цвет штриховки становился цветом линии (у знаков ЛГР он свой);
//   • точный шаг штриховки округлялся до ближайшего из трёх;
//   • у засечки терялись обводка (ow) и «не залитая» (filled: false).
// Ничего из этого человек не менял — оно пропадало само.
//
// И отдельно: «Применить к другим слоям» копировал fmt целиком, вместе с
// cats_off и cat_styles. Это ключи ЭТОГО слоя: список его скрытых категорий и
// правки, ключи которых суть знаки его объектов. На чужом слое они либо ни к
// чему не относятся, либо гасят его собственные категории с теми же знаками.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const src = читатьЧистый("app-style-ui.js");
const collect = src.slice(src.indexOf("const collect = ({ forceUniform"), src.indexOf('$("fmt-preset").addEventListener'));

// ---------- штриховка собирается ПОВЕРХ знака (в вынесенном помощнике) ----------
assert.match(collect, /собратьШтриховку\(fmt, \$, hObj, strokeCF\)/,
  "сборку штриховки обязано звать из collect");
const штрих = src.slice(src.indexOf("function собратьШтриховку"), src.indexOf("function собратьПодпись"));
assert.match(штрих, /fmt\.hatch = \{ \.\.\.дано,/,
  "штриховка обязана собираться поверх прежней, а не с нуля");
assert.match(штрих, /color: дано\.color \|\| strokeCF\.get\(\)/,
  "свой цвет штриховки знака обязан уцелеть; цвет линии — только когда своего нет");
assert.match(штрих, /тронули \? \(HATCH_DENS\[шаг\] \|\| 9\) : \(дано\.spacing_px \|\| 9\)/,
  "нетронутый список густоты показывает БЛИЖАЙШИЙ шаг к точному значению знака — " +
  "запись без проверки «сдвинули ли» подменяла бы точное значение шагом");
assert.match(штрих, /const тронули = шаг !== hatchDensOf\(дано\.spacing_px \|\| 9\);/,
  "«сдвинули ли список» определяется сравнением с тем же отображением, что его и заполнило");

// ---------- засечка тоже ----------
assert.match(collect, /fmt\.line_marker = \{\s*\n\s*\.\.\.\(baseMarker \|\| \{\}\),/,
  "у засечки есть свойства помимо четырёх правимых (обводка, заливка) — их нельзя терять");

// ---------- копирование на другие слои не тащит категории ----------
{
  const копия = src.slice(src.indexOf('$("fmt-copy").addEventListener'));
  const тело = копия.slice(0, копия.indexOf("renderLayers()"));
  assert.match(тело, /delete общий\.cats_off;/, "скрытые категории — свойство этого слоя");
  assert.match(тело, /delete общий\.cat_styles;/, "правки категорий — тоже");
  assert.match(тело, /l\.fmt = clone\(общий\);/,
    "каждому слою обязан достаться свой экземпляр, иначе правка одного меняет всех");
}

console.log("style-collect-keeps-sign: OK");
