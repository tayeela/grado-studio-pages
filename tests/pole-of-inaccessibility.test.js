"use strict";

// Полюс недоступности: точка, куда ставится подпись зоны и якорь TEXT в DXF.
//
// Сверено с эталоном mapbox/polylabel на восьми фигурах — подкова, гребёнка,
// бублик, щепка, Г-образная, звезда, дыра почти во весь контур, квадрат — и в
// местных координатах, и со сдвигом в МСК (413000, 6178000). Расстояние до
// границы совпадает всюду; расхождение у звезды укладывается в заданную
// точность и с ней же убывает (0.5 → 0.23, 0.01 → 0.003).
//
// А вот РЕАЛИЗАЦИЯ очереди была своя и дорогая: самая перспективная клетка
// искалась линейным просмотром, шаг стоил O(n) вместо O(log n). На фигуре с
// множеством отростков очередь разрастается, и цена растёт квадратично.
// Замер: гребёнка в 20 зубьев — 962 мс против 20 мс у эталона, в 48 раз.
// Почти секунда на ОДНУ подпись. Сверх того цикл был обвешан предохранителем
// `guard < 20000`, упирался в него на тех же фигурах и МОЛЧА возвращал
// недосчитанный ответ.
//
// После замены очереди на двоичную кучу: 32 мс, ответ совпадает с эталоном.

const assert = require("node:assert/strict");
const path = require("node:path");
const { читатьЧистый } = require("./_source");

global.window = global;
require(path.join(__dirname, "..", "app-labels.js"));
const L = global.GRADO_LABELS;
assert.ok(L && typeof L.poleOfInaccessibility === "function",
  "модуль подписей обязан подниматься без документа");

const прямоуг = (x, y, w, h) => [[x, y], [x + w, y], [x + w, y + h], [x, y + h]];
const сдвиг = (кольца, dx, dy) => кольца.map(r => r.map(([x, y]) => [x + dx, y + dy]));
const гребёнка = зубьев => {
  const p = [[0, 0]];
  for (let i = 0; i < зубьев; i++) { const x = i * 20; p.push([x + 5, 0], [x + 5, 800], [x + 15, 800], [x + 15, 0]); }
  p.push([зубьев * 20, 0], [зубьев * 20, -10], [0, -10]);
  return [p];
};

const ФИГУРЫ = {
  квадрат: [прямоуг(0, 0, 100, 100)],
  подкова: [[[0, 0], [100, 0], [100, 30], [30, 30], [30, 70], [100, 70], [100, 100], [0, 100]]],
  бублик: [прямоуг(0, 0, 100, 100), прямоуг(30, 30, 40, 40).reverse()],
  щепка: [[[0, 0], [300, 0], [300, 4], [0, 4]]],
  "Г-образная": [[[0, 0], [40, 0], [40, 80], [100, 80], [100, 100], [0, 100]]],
  "дыра почти во весь контур": [прямоуг(0, 0, 200, 100), прямоуг(10, 10, 150, 80).reverse()],
};
// Значения проверены против mapbox/polylabel при точности 0.5. Это не «что
// вернула наша функция вчера», а ответ эталонной реализации того же алгоритма.
const ЭТАЛОН = { квадрат: 50, подкова: 17.567, бублик: 17.567, щепка: 2,
  "Г-образная": 19.922, "дыра почти во весь контур": 19.922 };

// ---------- ответ совпадает с эталоном, и в МСК тоже ----------
for (const [имя, кольца] of Object.entries(ФИГУРЫ)) {
  for (const [метка, dx, dy] of [["", 0, 0], [" в МСК", 413000, 6178000]]) {
    const фигура = dx ? сдвиг(кольца, dx, dy) : кольца;
    const точка = L.poleOfInaccessibility(фигура, 0.5);
    const d = L.signedDistance(точка[0], точка[1], фигура);
    assert.ok(d > 0,
      `${имя}${метка}: подпись поставлена ВНЕ фигуры (расстояние ${d.toFixed(3)})`);
    assert.ok(Math.abs(d - ЭТАЛОН[имя]) <= 0.5,
      `${имя}${метка}: до границы ${d.toFixed(3)}, эталон polylabel ${ЭТАЛОН[имя]} — ` +
      "расхождение больше заданной точности");
  }
}

// ---------- ответ уточняется вместе с точностью ----------
{
  const звезда = [];
  for (let i = 0; i < 10; i++) {
    const a = Math.PI * i / 5 - Math.PI / 2, r = i % 2 ? 20 : 50;
    звезда.push([50 + r * Math.cos(a), 50 + r * Math.sin(a)]);
  }
  let прежнее = -Infinity;
  for (const точность of [0.5, 0.1, 0.01]) {
    const точка = L.poleOfInaccessibility([звезда], точность);
    const d = L.signedDistance(точка[0], точка[1], [звезда]);
    assert.ok(d >= прежнее - 1e-9,
      `звезда: с точностью ${точность} ответ стал ХУЖЕ (${d.toFixed(4)} после ${прежнее.toFixed(4)})`);
    assert.ok(Math.abs(20 - d) <= точность,
      `звезда: до границы ${d.toFixed(4)}, а точность обещана ${точность}`);
    прежнее = d;
  }
}

// ---------- цикл доходит до конца сам, а не упирается в предохранитель ----------
{
  const источник = читатьЧистый("app-labels.js");
  const тело = источник.slice(источник.indexOf("function poleOfInaccessibility"));
  const конец = тело.slice(0, тело.indexOf("\n  }") + 4);
  assert.doesNotMatch(конец, /guard/,
    "предохранитель на числе шагов молча обрезал ответ на фигурах со множеством " +
    "отростков: он прикрывал не переполнение, а медленную очередь");
  assert.match(конец, /queue\.pop\(\)/,
    "клетка обязана доставаться из кучи, а не выбираться перебором массива");
  assert.match(источник, /class MaxHeap/,
    "очередь по приоритету — двоичная куча: перебор давал O(n) на шаг");
}

// ---------- цена шага: гребёнка не должна занимать секунду ----------
{
  const фигура = гребёнка(20);
  const начало = process.hrtime.bigint();
  const точка = L.poleOfInaccessibility(фигура, 0.5);
  const мс = Number(process.hrtime.bigint() - начало) / 1e6;
  assert.ok(L.signedDistance(точка[0], точка[1], фигура) > 0, "гребёнка: точка обязана быть внутри");
  // замер: 962 мс перебором, 32 мс кучей, 20 мс у эталона. Потолок с запасом —
  // сторож ловит возврат к перебору, а не колебания машины.
  assert.ok(мс < 300,
    `гребёнка в 20 зубьев считалась ${мс.toFixed(0)} мс — очередь снова линейная?`);
}

console.log("pole-of-inaccessibility: OK");
