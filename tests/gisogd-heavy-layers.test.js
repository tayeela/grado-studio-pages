"use strict";

// Слои ГИС ОГД, которые целиком в браузер не помещаются.
//
// «Земельные участки» (zu_29_06_2021) — это ВСЕ участки Москвы. Замер: 269 МБ
// за 560 с, и это ещё не конец файла (скорость 480 КБ/с). Портал не умеет
// отдавать слой по области: у `export/` единственный параметр — `format`,
// ни bbox, ни limit, ни тайлов (проверено на API 2.8, всё остальное — 404).
//
// Прежде такой слой дважды по две минуты упирался в таймаут, а когда
// зависание пофиксили — стал ФЛАГОМ ПОЛНОГО ОТКАЗА: сообщение «слишком
// большой» и всё, хотя граница у портала — по формату файла, а не по
// содержимому: он неспособен резать по bbox, а не неспособен ОТДАТЬ область.
//
// Резать умеет НАША сторона: makeFeatureSplitter отдаёт объекты по мере
// разбора потока, featureHitsBbox тут же решает, входит объект в площадку.
// Портал всё равно шлёт файл целиком (другого не умеет), но в памяти и в
// кэше остаётся только выбранная область. Значит вместо отказа — честный
// опрос ДО закачки: сколько весит, сколько займёт, что именно сохранится, и
// что отменить можно в любой момент. НСПД называется тут же как быстрая
// замена для тех, кто ждать не хочет.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const adapter = читатьЧистый("pages-adapter.js");

// ---------- список тяжёлых слоёв есть и несёт цену, а не только имя ----------
{
  assert.match(adapter, /const GISOGD_TOO_BIG = \{/,
    "список неподъёмных слоёв обязан существовать: без него каждый упрётся в таймаут");
  assert.match(adapter, /zu_29_06_2021: \{/,
    "«Земельные участки» — известный неподъёмный слой (269+ МБ)");
  const начало = adapter.indexOf("const GISOGD_TOO_BIG");
  const блок = adapter.slice(начало, adapter.indexOf("};", начало));
  assert.match(блок, /bytes: 269 \* 1024 \* 1024/, "размер обязан быть числом, а не только словами в тексте");
  assert.match(блок, /НСПД/,
    "быстрая замена обязана называться: те же участки ЕГРН есть в НСПД");
}

// ---------- слой не течёт в общий кэш и в память целиком ----------
{
  const тело = adapter.slice(adapter.indexOf("async function gisogdLayerJson("));
  assert.match(тело, /if \(heavy\) \{/, "неподъёмный слой обязан идти отдельным путём");
  const heavyТело = тело.slice(тело.indexOf("if (heavy) {"), тело.indexOf("// 300 с вместо 120"));
  assert.match(heavyТело, /streamGisogdFiltered\(/,
    "качается потоком с отбором по области, а не JSON\\.parse всего файла");
  assert.ok(!/const response = await externalFetch[\s\S]{0,80}readWithProgress/.test(heavyТело),
    "неподъёмный слой не должен идти через тот же путь, что копит весь текст в памяти");
}

// ---------- опрос честный: размер, время, что сохранится, отмена ----------
{
  const тело = adapter.slice(adapter.indexOf("async function gisogdLayerJson("));
  const heavyТело = тело.slice(тело.indexOf("if (heavy) {"), тело.indexOf("// 300 с вместо 120"));
  assert.match(heavyТело, /uiConfirm\(/, "решение — за человеком, а не за кодом");
  assert.match(heavyТело, /formatBytes\(bytes\)/, "размер называется числом, а не «слишком большой»");
  assert.match(heavyТело, /minutes/, "время называется, а не только вес");
  assert.match(heavyТело, /В браузере останется только ВАША площадка/,
    "человек обязан знать: сохранится область, а не весь 269-мегабайтный файл");
  assert.match(heavyТело, /Отменить можно в любой момент/,
    "закачка на девять минут без явной кнопки отмены — ловушка, а не выбор");
  assert.match(heavyТело, /stop\.name = "GradoUserDeclined"/,
    "отказ — не сбой сети: у него своё имя, как и у обычного большого слоя");
}

// ---------- цена в минутах меряется, а не гадается ----------
assert.match(adapter, /const GISOGD_STREAM_BYTES_PER_SEC = 480 \* 1024;/,
  "скорость — измеренное число (480 КБ/с), а не круглая оценка на глаз");
assert.match(adapter, /const bytes = knownBytes \|\| heavy\.bytes;/,
  "после первой закачки цена считается по РЕАЛЬНОМУ измеренному весу, а не по " +
  "оценке из справочника — knownBytes обязан выигрывать");

// ---------- кэш ключуется площадкой ----------
{
  assert.match(adapter, /const hashBbox = bbox =>/, "у площадки обязан быть свой ключ кэша");
  assert.match(adapter, /const gisogdFilteredCode = \(code, bbox\) => `\$\{code\}_b\$\{hashBbox\(bbox\)\}`;/,
    "ключ обязан зависеть и от слоя, и от площадки — иначе вторая площадка " +
    "перезапишет кэш первой или получит чужие объекты");
  assert.match(adapter, /const cacheCode = heavy && bbox \? gisogdFilteredCode\(code, bbox\) : code;/,
    "обычные слои кэшируются как раньше, по одному только коду");
}

// ---------- таймаут не тот же, что у помещающихся слоёв ----------
assert.match(adapter, /pagesCore\.gisogdLayerUrl\(code\), \{ signal \}, 900000\)/,
  "269 МБ на 480 КБ/с — это ~560 с; 300 с (таймаут обычных слоёв ОГД) обрежет закачку на середине");

console.log("gisogd-heavy-layers: OK");
