"use strict";

// Слои ГИС ОГД, которые целиком в браузер не помещаются.
//
// «Земельные участки» (zu_29_06_2021) — это ВСЕ участки Москвы. Замер: 269 МБ
// за 560 с, и это ещё не конец файла (скорость 480 КБ/с). Портал не умеет
// отдавать слой по области: у `export/` единственный параметр — `format`,
// ни bbox, ни limit, ни тайлов (проверено на API 2.8, всё остальное — 404).
//
// Прежде такой слой дважды по две минуты упирался в таймаут и выдавал
// «не ответил за 120 с — попробуйте позже». Позже не поможет никогда: слой
// не станет меньше. Человек ждёт четыре минуты и остаётся ни с чем.
//
// Теперь про такие слои говорится сразу и называется рабочая замена: те же
// границы ЕГРН приходят из НСПД по площадке за доли секунды. Проверено
// сравнением 105 пар: после датум-поправки медиана расхождения 0.10 м,
// 86 % участков ближе 30 см.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const adapter = читатьЧистый("pages-adapter.js");

// ---------- список тяжёлых слоёв есть и проверяется ДО запроса ----------
{
  assert.match(adapter, /const GISOGD_TOO_BIG = \{/,
    "список неподъёмных слоёв обязан существовать: иначе каждый упрётся в таймаут");
  assert.match(adapter, /zu_29_06_2021:/,
    "«Земельные участки» — известный неподъёмный слой (269+ МБ)");

  const проверка = adapter.indexOf("if (GISOGD_TOO_BIG[code]) throw");
  const запрос = adapter.indexOf("pagesCore.gisogdLayerUrl(code)");
  assert.ok(проверка > 0 && проверка < запрос,
    "проверять надо ДО запроса: смысл в том, чтобы не ждать впустую");
}

// ---------- сообщение называет замену, а не просто отказывает ----------
{
  const начало = adapter.indexOf("const GISOGD_TOO_BIG");
  const блок = adapter.slice(начало, adapter.indexOf("};", начало));
  assert.match(блок, /НСПД/,
    "отказ обязан называть рабочий источник: те же участки ЕГРН есть в НСПД");
  assert.match(блок, /МБ/,
    "и объяснять причину размером, а не общими словами");
}

// ---------- таймаут слоя больше, чем у обычных источников ----------
{
  assert.match(adapter, /gisogdLayerUrl\(code\), \{ signal \}, 300000\)/,
    "слои ОГД качаются целиком: 120 с не хватало даже тем, что помещаются " +
    "(ГПЗУ — 97 МБ), и они обрывались на полпути");
}

console.log("gisogd-heavy-layers: OK");
