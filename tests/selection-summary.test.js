"use strict";

// Сводка по выборке.
//
// Отвечает на вопрос, который в работе задают каждый день: «сколько гектаров
// жилой застройки попало в границу». Числа отсюда уходят в пояснительную
// записку, поэтому проверяются на геометрии с известным ответом.

const assert = require("node:assert/strict");
const { selectionSummary, summaryText } = require("../app-summary.js");

const близко = (a, b, ε, что) => assert.ok(Math.abs(a - b) < ε,
  `${что}: ожидалось ${b}, получено ${a}`);

const квадрат = (x, y, сторона, props) => ({
  ring: [[x, y], [x + сторона, y], [x + сторона, y + сторона], [x, y + сторона]], props });

// ---------- итог без разбивки ----------
{
  const с = selectionSummary([квадрат(0, 0, 100, {}), квадрат(200, 0, 50, {})], {});
  assert.equal(с.итог.количество, 2, "два объекта");
  близко(с.итог.площадь, 10000 + 2500, 1e-6, "сумма площадей");
  близко(с.итог.длина, 400 + 200, 1e-6, "сумма периметров");
  assert.deepEqual(с.группы, [], "без поля групп нет");
}

// ---------- разбивка по значению поля ----------
{
  const объекты = [
    квадрат(0, 0, 100, { назначение: "жилое" }),
    квадрат(200, 0, 100, { назначение: "жилое" }),
    квадрат(400, 0, 50, { назначение: "общественное" }),
  ];
  const с = selectionSummary(объекты, { field: "назначение" });
  assert.equal(с.группы.length, 2, "две группы");
  assert.equal(с.группы[0].значение, "жилое", "крупнейшая группа первой");
  близко(с.группы[0].площадь, 20000, 1e-6, "жилое: два по гектару");
  assert.equal(с.группы[0].количество, 2);
  близко(с.группы[0].доля, 20000 / 22500, 1e-9, "доля считается от общей площади");
  близко(с.группы[1].площадь, 2500, 1e-6, "общественное");
  близко(с.итог.площадь, 22500, 1e-6, "итог сходится с суммой групп");
}

// ---------- пустое значение не теряется ----------
{
  // «В сводке 40 га, а в слое 60» — ошибка, которую ищут полдня. Объект без
  // значения обязан попасть в свою группу, а не исчезнуть.
  const с = selectionSummary([
    квадрат(0, 0, 100, { назначение: "жилое" }),
    квадрат(200, 0, 100, {}),
    квадрат(400, 0, 100, { назначение: "" }),
  ], { field: "назначение" });
  const пустая = с.группы.find(г => г.значение === "— не задано —");
  assert.ok(пустая, "группа для пустых значений существует");
  assert.equal(пустая.количество, 2, "и пропуск, и пустая строка — оба сюда");
  близко(с.итог.площадь, 30000, 1e-6, "итог считает все три");
}

// ---------- дыра не считается площадью ----------
{
  const сДырой = {
    ring: [[0, 0], [100, 0], [100, 100], [0, 100]],
    holes: [[[40, 40], [60, 40], [60, 60], [40, 60]]],
    props: { назначение: "жилое" } };
  const с = selectionSummary([сДырой], {});
  близко(с.итог.площадь, 10000 - 400, 1e-6,
    "выколотая часть объекту не принадлежит — иначе гектары разойдутся с ТЭП");
}

// ---------- линии дают длину, но не площадь ----------
{
  const с = selectionSummary([{ line: [[0, 0], [0, 250]], props: { тип: "проезд" } }],
    { field: "тип" });
  близко(с.итог.длина, 250, 1e-9, "длина ломаной");
  assert.equal(с.итог.площадь, 0, "у линии площади нет");
  близко(с.группы[0].доля, 1, 1e-9, "при нулевой площади доля считается по числу");
}

// ---------- пустая выборка не ломает счёт ----------
{
  const с = selectionSummary([], { field: "назначение" });
  assert.deepEqual(с.итог, { количество: 0, площадь: 0, длина: 0 });
  assert.deepEqual(с.группы, []);
}

// ---------- текст вставляется таблицей ----------
{
  const с = selectionSummary([
    квадрат(0, 0, 100, { назначение: "жилое" }),
    квадрат(200, 0, 50, { назначение: "общественное" }),
  ], { field: "назначение" });
  const строки = summaryText(с, "назначение").split("\n");
  assert.equal(строки.length, 4, "шапка, две группы и итог");
  assert.match(строки[0], /Площадь, м²\tПлощадь, га/, "и метры, и гектары");
  assert.match(строки[3], /^Итого\t2\t12500\.00\t1\.2500\t/, "итоговая строка");
  assert.equal(строки[1].split("\t").length, 6, "шесть столбцов через табуляцию");
}

console.log("selection-summary: OK");
