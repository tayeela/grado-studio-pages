"use strict";

// Ритуал версии.
//
// Номер сборки живёт в index.html почти шестью десятками мест: `?v=NNNNN` у
// каждого скрипта и стиля плюс объявление `window.__GRADO_ASSET_VERSION__`,
// и ещё раз — в version.json. Все они обязаны совпадать: `?v=` управляет
// кэшем GitHub Pages, переменная — тем, что приложение сообщает о себе,
// version.json — тем, что видит проверка обновления.
//
// Разъезд ловится не сразу и врёт молча. Поймано на живой проверке: бамп шёл
// заменой по шаблону `?v=10124`, объявление переменной такого шаблона не
// содержит — скрипты уехали на 10125, переменная осталась на 10124. Прод-
// проверки читают именно переменную, то есть подтвердили бы выкладку, которой
// нет. Причина в том, что ритуал выполняется вручную и каждый раз немного
// другой командой; сторож делает разницу видимой сразу.

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const version = JSON.parse(fs.readFileSync(path.join(root, "version.json"), "utf8"));

// ---------- все ?v= одинаковы ----------
const метки = [...html.matchAll(/\?v=(\d+)/g)].map(m => m[1]);
assert.ok(метки.length > 30,
  `меток ?v= всего ${метки.length} — разбор сломался, сторож ослеп`);
const уникальные = [...new Set(метки)];
assert.equal(уникальные.length, 1,
  `в index.html разные версии ассетов: ${уникальные.join(", ")} — ` +
  "часть файлов придёт из кэша, часть свежая, и приложение соберётся из двух сборок");

// ---------- объявленная версия совпадает с метками ----------
const объявлена = (html.match(/__GRADO_ASSET_VERSION__\s*=\s*"(\d+)"/) || [])[1];
assert.ok(объявлена, "window.__GRADO_ASSET_VERSION__ обязан быть объявлен в index.html");
assert.equal(объявлена, уникальные[0],
  `приложение сообщает о себе версию ${объявлена}, а файлы грузит с ?v=${уникальные[0]}. ` +
  "Прод-проверка читает именно переменную — она подтвердит выкладку, которой нет.");

// ---------- version.json не отстаёт ----------
assert.equal(String(version.bundle_version), уникальные[0],
  `version.json обещает ${version.bundle_version}, а index.html собран на ${уникальные[0]} — ` +
  "проверка обновления будет звать перезагрузиться на уже загруженную версию");

console.log(`version-ritual: OK (сборка ${уникальные[0]}, меток ${метки.length})`);
