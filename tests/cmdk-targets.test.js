"use strict";

// Командная палитра предлагала команду, которой больше нет.
//
// Демо-проект удалили целиком (коммит a8604b6): кнопка btn-demo и строка меню
// исчезли из разметки. А в палитре ⌘K строка «Заполнить примером (демо)»
// осталась и вела на click("btn-demo"), где стоял молчаливый выход по !element.
// Замер: команда в списке есть, ищется поиском, выбирается — и не делает
// ничего, без единого слова. Человеку это читается как «функция сломалась».
//
// Беда не в одной строке, а в связи: палитра ссылается на разметку по
// СТРОКОВЫМ идентификаторам, и компилятор такую связь не проверяет. Значит
// проверять обязан сторож — иначе следующее переименование кнопки повторит
// историю. Тот же разрыв возможен и для инструментов (data-tool), и для
// глобальных функций, которые палитра дёргает через window.

const assert = require("node:assert/strict");
const { читать, читатьЧистый } = require("./_source");

const cmdk = читатьЧистый("redesign/cmdk.js");
const html = читать("index.html");

const собрать = (текст, шаблон) => [...new Set(
  [...текст.matchAll(шаблон)].map(m => m[1]))].sort();

// ---- 1. каждая кнопка, на которую ссылается палитра, есть в разметке ----
const кнопки = собрать(cmdk, /\bclick\("([a-z0-9-]+)"\)/g);
assert.ok(кнопки.length > 15,
  `команд с кнопками должно быть много, найдено ${кнопки.length} — сломался разбор`);
const нетВРазметке = кнопки.filter(id => !new RegExp(`id="${id}"`).test(html));
assert.deepEqual(нетВРазметке, [],
  "палитра ссылается на кнопки, которых нет в index.html: " + нетВРазметке.join(", "));

// ---- 2. каждый инструмент палитры есть на рельсе ----
const инструменты = собрать(cmdk, /\btool\("([a-z]+)"\)/g);
assert.ok(инструменты.length > 15,
  `инструментов должно быть много, найдено ${инструменты.length} — сломался разбор`);
const нетНаРельсе = инструменты.filter(name => !new RegExp(`data-tool="${name}"`).test(html));
assert.deepEqual(нетНаРельсе, [],
  "палитра ссылается на инструменты, которых нет на рельсе: " + нетНаРельсе.join(", "));

// ---- 3. молчаливого выхода при пропавшей кнопке больше нет ----
const тело = cmdk.slice(cmdk.indexOf("const click = id =>"));
const телоClick = тело.slice(0, тело.indexOf("\n  };") + 4);
assert.doesNotMatch(телоClick, /if \(!e\) return;/,
  "пропавшая кнопка обязана быть слышна: молчаливый выход и породил мёртвую строку");
assert.match(телоClick, /if \(!e\) \{[\s\S]{0,400}toast\(/,
  "при пропавшей кнопке палитра обязана сказать это вслух, а не притвориться сработавшей");

// ---- 4. демо-проекта нет ни в разметке, ни в палитре ----
assert.doesNotMatch(cmdk, /btn-demo/,
  "демо-проект удалён вместе с кнопкой — команды на него быть не должно");

console.log("cmdk-targets: OK");
