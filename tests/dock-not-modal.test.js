"use strict";

// Окно в рабочей панели (док) считалось модальным — и вело себя как ловушка.
//
// Док заведён ровно затем, чтобы работать ГЛЯДЯ НА ЧЕРТЁЖ: окно стоит сбоку,
// холст рядом виден и кликабелен. Но разметка окна при переезде не меняется
// (dock.js только вешает класс .docked), поэтому слой доступности продолжал
// считать его модальным диалогом. Замеры до правки:
//
//  * Tab внутри дока ходил по кругу: 8 нажатий — 8 переходов, все внутри
//    панели, ни одного наружу. На холст, рельс инструментов и панель слоёв
//    с клавиатуры было не попасть вовсе;
//  * на .modal висел aria-modal="true" — чтец прятал от человека весь
//    остальной интерфейс, хотя тот виден и работает;
//  * «Знаки проекта» по Escape не закрывались ВООБЩЕ: перехватчик диалогов
//    жал кнопку закрытия, та зовёт closePopups, а closePopups докированные
//    окна не трогает — и окно оставалось в доке;
//  * одно нажатие Escape при модалке поверх дока закрывало ОБА окна:
//    обработчик модалки успевал снять её со страницы, и док, проверявший
//    наличие модалки по разметке, видел пустоту и закрывался за компанию.
//
// Общая причина одна: «поверх» и «сбоку» считались одним и тем же. Сторож
// проверяет, что все три места сходятся на одном признаке — .docked.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const a11y = читатьЧистый("redesign/a11y.js");
const dock = читатьЧистый("redesign/dock.js");
const panel = читатьЧистый("app-layer-panel.js");

// ---- 1. ловушка фокуса и перехват Escape — только для НЕдокированных ----
const обработчик = a11y.slice(a11y.indexOf("const overlays = ["));
assert.ok(обработчик.length > 0, "перечень окон в обработчике клавиш обязан остаться находимым");
assert.match(обработчик, /querySelectorAll\('\.modal-overlay:not\(\.docked\)'\)/,
  "ловушка Tab и перехват Escape не должны распространяться на окно, стоящее сбоку");
assert.ok(/if \(event\.key === 'Tab' && dialog\)/.test(a11y),
  "для настоящих модальных окон ловушка Tab обязана остаться: без неё фокус уходит за окно");

// ---- 2. модальность пересчитывается по месту, а не задаётся навсегда ----
assert.match(a11y, /aria-modal', String\(!docked\(overlay\)\)\)/,
  "aria-modal обязан считаться от того, где окно стоит сейчас, а не от того, как оно создано");
assert.ok(a11y.indexOf("syncDialogModality()") < a11y.lastIndexOf("syncDialogModality()"),
  "пересчёт обязан вызываться не только при запуске: окно переезжает в док уже после создания");
const наблюдатель = a11y.slice(a11y.indexOf("new MutationObserver"), a11y.indexOf("observer.observe"));
assert.match(наблюдатель, /syncDialogModality\(\);/,
  "переезд окна в док — это правка class или перенос узла; оба вида доходят до наблюдателя");

// ---- 3. «верхнее окно» для Escape — тоже без докированных ----
const верхнее = panel.slice(panel.indexOf("function topOverlay()"),
  panel.indexOf("}", panel.indexOf("function topOverlay()")) + 1);
assert.match(верхнее, /\.modal-overlay:not\(\.docked\)/,
  "докированное окно не «верхнее»: закрывает его док своим способом, " +
  "который умеет добить окно, закрывающееся через closePopups");

// ---- 4. одно нажатие Escape — одно окно ----
const докEscape = dock.slice(dock.indexOf('if (event.key !== "Escape"'));
assert.match(докEscape, /if \(event\.defaultPrevented\) return;/,
  "проверять наличие модалки по разметке поздно — её обработчик стоит раньше " +
  "и успевает её снять; признак «Escape уже потрачен» живёт в самом событии");
assert.ok(докEscape.indexOf("event.defaultPrevented") <
  докEscape.indexOf('querySelector(".modal-overlay:not(.docked)")'),
  "признак из события обязан проверяться ДО проверки по разметке: разметка уже устарела");

console.log("dock-not-modal: OK");
