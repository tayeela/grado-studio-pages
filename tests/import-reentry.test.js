"use strict";

// Двойной клик по «Импортировать» запускал второй разбор параллельно.
//
// Замер до правки: два вызова importPickedFiles с одним и тем же файлом дают
// ДВА одинаковых окна «Импортировать «X»?» одно поверх другого и два запроса
// на сервер за одно действие человека. Он отвечает на один и тот же вопрос
// дважды и не понимает, почему его спрашивают снова.
//
// Полоса занятости (beginBusy) от этого не защищает и защищать не должна:
// она рисует прогресс, а не держит замок. Счётчик в ней как раз рассчитан на
// несколько одновременных работ.
//
// Замер после: одно окно, второй вызов говорит вслух «Импорт уже идёт».
// Замок отпускается и после успеха, и после отказа в окне подтверждения —
// проверено подряд идущими импортами (2 → 3 объекта) и импортом после отмены.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

const источник = читатьЧистый("app-import-files.js");
const начало = источник.indexOf("async function importPickedFiles");
assert.ok(начало > 0, "точка входа импорта обязана оставаться находимой");
const тело = источник.slice(начало, источник.indexOf("root.importPickedFiles"));

// ---------- повторный запуск не начинает вторую работу ----------
assert.match(тело, /if \(идётИмпорт\) \{[\s\S]{0,200}return;/,
  "пока идёт разбор, второй запуск обязан вернуться, а не пойти параллельно");
assert.match(тело, /if \(идётИмпорт\) \{[\s\S]{0,160}toast\(/,
  "и сказать это вслух: молчаливый выход человек прочитает как «кнопка не работает»");

// ---------- замок снимается при любом исходе ----------
assert.match(тело, /\} finally \{[^}]*идётИмпорт = false;/,
  "снимать замок обязано finally: при исключении в разборе (битый ZIP, отказ " +
  "сервера) импорт иначе умрёт до перезагрузки страницы");
const до = тело.indexOf("идётИмпорт = true;");
const после = тело.indexOf("идётИмпорт = false;");
assert.ok(до > 0 && после > до, "замок ставится до работы и снимается после неё");

// ---------- полоса занятости замком не считается ----------
{
  const shell = читатьЧистый("app-shell.js");
  const busy = shell.slice(shell.indexOf("function beginBusy"), shell.indexOf("function setBusyProgress"));
  assert.match(busy, /_busyCount\+\+/,
    "beginBusy считает одновременные работы — это индикатор, а не замок; " +
    "защита от повторного запуска обязана жить у самой операции");
}

console.log("import-reentry: OK");
