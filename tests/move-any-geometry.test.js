"use strict";

// Круг и дугу нельзя было перетащить мышью.
//
// featureMovablePts отдаёт ЖИВЫЕ точки кольца и ломаной — правь и объект едет.
// У круга и дуги живых точек нет: featurePts вычисляет их заново на каждый
// вызов, и правка уходит в копию. Три места это знали и обходили вручную
// (буфер обмена, сдвиг слоя, трансформации), а четвёртое — само перетаскивание
// — забыли. Объект под курсором молча стоял на месте.
//
// Проверяем ОБЩЕЕ место (featureMoveOrigin + moveFeatureFrom) и то, что
// перетаскивание зовёт именно его, а не двигает точки само.

const assert = require("node:assert/strict");
const vm = require("node:vm");
const источник = require("./_source");

const геодезия = источник.читатьЧистый("app-geodesy.js");
const начало = геодезия.indexOf("function featureMovablePts(");
const конец = геодезия.indexOf("function arcScreenArgs(");   // читатьЧистый снимает комментарии — якорь только по коду
assert.ok(начало > 0 && конец > начало, "перенос обязан оставаться извлекаемым");

const среда = vm.createContext({ featureRings: f => (f.ring ? [f.ring] : []) });
vm.runInContext(геодезия.slice(начало, конец), среда);
const { featureMoveOrigin, moveFeatureFrom } = среда;

const перенести = (f, dx, dy) => { moveFeatureFrom(f, featureMoveOrigin(f), dx, dy); return f; };

// ---- круг едет целиком, радиус не трогается ----
const круг = перенести({ circle: { cx: 0, cy: 0, r: 50 } }, 100, 20);
assert.deepEqual([круг.circle.cx, круг.circle.cy], [100, 20], "круг обязан переехать за центр");
assert.equal(круг.circle.r, 50, "радиус при переносе не меняется");

// ---- дуга едет целиком, разворот не трогается ----
const дуга = перенести({ arc: { cx: 0, cy: 0, r: 50, a0: 0.3, sweep: 1.2 } }, -10, 5);
assert.deepEqual([дуга.arc.cx, дуга.arc.cy], [-10, 5], "дуга обязана переехать за центр");
assert.equal(дуга.arc.sweep, 1.2, "разворот дуги при переносе не меняется");
assert.equal(дуга.arc.a0, 0.3, "начальный угол дуги тоже");

// ---- кольцо едет повершинно ----
const кольцо = перенести({ ring: [[0, 0], [10, 0], [10, 10]] }, 100, 20);
assert.deepEqual(кольцо.ring, [[100, 20], [110, 20], [110, 30]], "кольцо едет каждой вершиной");

// ---- повторный перенос считается от НОВОГО положения ----
перенести(круг, 5, 5);
assert.deepEqual([круг.circle.cx, круг.circle.cy], [105, 25],
  "второй перенос отсчитывается от текущего положения, а не от исходного");

// ---- перетаскивание мышью пользуется общим местом ----
const ввод = источник.читатьЧистый("app-input.js");
assert.match(ввод, /const orig = feats\.map\(ff => featureMoveOrigin\(ff\)\);/,
  "перетаскивание обязано снимать исходное положение общей функцией");
assert.match(ввод, /moveFeatureFrom\(feat, ed\.orig\[fi\], ox, oy\);/,
  "и переносить объект ею же, иначе круг с дугой снова замрут");

console.log("move-any-geometry: OK");
