"use strict";

// Цепочка размеров.
//
// Размеры по фасаду или по красной линии ставят подряд от общей выносной.
// Без цепочки во вторую точку предыдущего размера приходится целиться заново —
// это лишняя работа и лишняя погрешность: привязка может взять соседний узел,
// и цепочка разъедется на десятые доли метра, которые потом всплывут в
// ведомости координат.
//
// Enter при активном «Размере» и пустом холсте начинает новый размер от конца
// предыдущего. Живая проверка: второй размер начался ровно в точке окончания
// первого, смена инструмента цепочку гасит.

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const input = fs.readFileSync(path.join(root, "app-input.js"), "utf8");
const shell = fs.readFileSync(path.join(root, "app-shell.js"), "utf8");

// ---------- конец размера запоминается ----------
assert.match(input, /state\.dimLast = pts\[1\]/,
  "без конца предыдущего размера продолжать нечего");

// ---------- Enter продолжает, но НЕ ломает начатое ----------
{
  const начало = input.indexOf('if (state.tool === "dim" && !state.drawing && state.dimLast)');
  assert.ok(начало > 0,
    "цепочка обязана требовать пустой холст: иначе Enter перестанет завершать начатую фигуру");
  const блок = input.slice(начало, начало + 400);
  assert.match(блок, /state\.drawing = \{ pts: \[state\.dimLast/,
    "новый размер начинается ИМЕННО от конца предыдущего");
  assert.match(блок, /\.slice\(\)/,
    "точку копируем: правка нового размера не должна двигать предыдущий");

  // порядок важен: ветка цепочки стоит ДО общего завершения фигуры
  const общее = input.indexOf("if (state.drawing && state.typed) placeTypedPoint();", начало);
  assert.ok(общее > начало,
    "ветка цепочки обязана стоять до общего Enter-завершения, иначе не сработает");
}

// ---------- уход с инструмента гасит цепочку ----------
assert.match(shell, /if \(tool !== "dim"\) state\.dimLast = null;/,
  "иначе цепочка оживёт через полчаса от точки, которую человек уже не помнит");

// ---------- человеку сказано, что цепочка есть ----------
{
  assert.match(shell, /«Размер»[^"]*Enter — цепочка/,
    "возможность, о которой не сказано в подсказке, не существует");
  assert.match(input, /цепочка от последней точки|цепочка от предыдущего/,
    "после первого размера подсказка обязана звать продолжить");
}

console.log("dim-chain: OK");
