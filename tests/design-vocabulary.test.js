"use strict";

// Словарь оформления.
//
// Ощущение «навайбкодено» берётся не из отдельной кривой кнопки, а из того,
// что соседние блоки нарисованы по разным правилам: тут радиус 6, там 5, у
// одной кнопки вес 650, у соседней 600. Глаз это замечает, даже когда не может
// назвать причину.
//
// Замер до правки: 19 радиусов, 11 весов шрифта. Сведено к токенам — 57
// радиусов и 136 весов переписаны, и при этом НЕ СДВИНУЛАСЬ раскладка: из
// девяти опорных узлов изменилось одно свойство (вес кнопки 650 → 600), ширина
// двух подписей — на пиксель.
//
// Детектор держит словарь закрытым: новое сырое значение обязано быть либо
// осознанным исключением из списка ниже, либо токеном.

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const ФАЙЛЫ = ["tokens.css", "redesign/shell.css", "redesign/studio2.css",
  "redesign/atelier.css", "redesign/layers-studio.css"];
const css = ФАЙЛЫ.map(f => fs.readFileSync(path.join(root, f), "utf8")).join("\n");

// Значения, которые токеном не выражаются и оставлены сознательно.
const МОЖНО = {
  "border-radius": new Set([
    "0", "50%", "inherit",
    "0 2px 2px 0",             // скругление только правых углов
    "0 0 8px 8px",             // низ выпадающего блока
    "0 0 var(--r-sm) var(--r-sm)",
  ]),
  "font-weight": new Set([
    "400",                     // объявление токена --fw-regular
    "100 900",                 // диапазон осей переменного шрифта
    "inherit", "bold", "normal",
  ]),
};

function значения(свойство) {
  const re = new RegExp(свойство + ":\\s*([^;}!]+)", "g");
  const все = [...css.matchAll(re)].map(m => m[1].trim());
  return все.filter(v => !v.startsWith("var(") && !МОЖНО[свойство].has(v));
}

for (const свойство of ["border-radius", "font-weight"]) {
  const сырые = значения(свойство);
  assert.equal(сырые.length, 0,
    `${свойство}: значение мимо токенов — словарь снова расползается.\n  ` +
    [...new Set(сырые)].join("\n  ") +
    "\n  Возьмите ближайший токен или добавьте новый осознанно, а не число по месту.");
}

// ---------- лестница токенов не растёт бесконтрольно ----------
{
  // Считаем ИМЕНА, а не объявления, и требуем, чтобы имя объявлялось ровно
  // один раз. Второе объявление тех же имён — как было в atelier.css — делает
  // tokens.css ложью: правка «по токенам» молча меняет вид.
  const радиусы = [...css.matchAll(/(--r-[\w-]+):\s*([^;]+);/g)].map(m => m[1]);
  const повторы = радиусы.filter((имя, i) => радиусы.indexOf(имя) !== i);
  assert.deepEqual(повторы, [],
    `радиус объявлен дважды: ${[...new Set(повторы)].join(", ")} — ` +
    "шкала должна жить в одном месте, иначе tokens.css врёт о действующих значениях");
  assert.ok(new Set(радиусы).size <= 6,
    `радиусов в лестнице ${new Set(радиусы).size} — больше шести это уже не система`);
  const веса = [...css.matchAll(/--fw-[\w-]+:\s*([^;]+);/g)].map(m => m[1].trim());
  assert.ok(веса.length <= 4,
    `весов в лестнице ${веса.length}: ${веса.join(", ")} — четырёх хватает на любой интерфейс`);
}

// ---------- настоящие тени высоты — только из лестницы ----------
{
  // inset-тени тут не считаем: ими рисуют рамки и акцентные полосы, а не высоту.
  const тени = [...css.matchAll(/box-shadow:\s*([^;}!]+)/g)].map(m => m[1].trim())
    .filter(v => !v.startsWith("inset") && v !== "none" && !v.startsWith("var("));
  const высотные = тени.filter(v => /\d+px\s+\d+px\s+\d\d+px/.test(v));   // размытие ≥10px
  assert.equal(высотные.length, 0,
    "тень высоты мимо лестницы --shadow-*:\n  " + [...new Set(высотные)].join("\n  ") +
    "\n  Высота у интерфейса одна на всех — иначе панели висят на разной высоте без причины.");
}

