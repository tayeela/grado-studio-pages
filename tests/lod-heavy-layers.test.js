"use strict";

// Уровень детализации на тяжёлых слоях.
//
// Замер на городском слое: 100 000 зданий давали 1504 мс на кадр, из них три
// четверти — растеризация (заливка ста тысяч контуров ≈ 950 мс). Объект,
// занимающий на экране полтора пикселя, рисуется одним прямоугольником по
// габариту: 1504 → 252 мс, а картинка при этом неотличима — средний цвет
// сдвинулся на единицу из 255, закрашенных пикселей столько же.
//
// Опасность здесь одна и серьёзная: если упрощение протечёт в ВЫПУСК, чертёж
// уйдёт заказчику без деталей, и никто этого не заметит. Поэтому условия
// применения стережём тестом — каждое из них про правильность, а не скорость.

const assert = require("node:assert/strict");
const app = require("./app-source");

// ---------- порог объявлен явно ----------
assert.match(app, /const LOD_PX = [\d.]+;/,
  "порог уровня детализации обязан быть именованной константой, а не числом в коде");

// ---------- участок кода, где решается упрощение ----------
const начало = app.indexOf("function drawTinyRing(f, st)");
assert.ok(начало > 0, "drawTinyRing не найдена — упрощение исчезло или переименовано");
const блок = app.slice(начало, начало + 1400);

// ---------- 1. на листе — никогда ----------
assert.ok(блок.includes("if (_renderTarget ||"),
  "лист обязан отсекаться первым: выпуск не имеет права терять детали");

// ---------- 2. выделенное — никогда ----------
assert.ok(блок.includes("if (state.selectedIds.has(f.id)) return false;"),
  "выделенный объект человек рассматривает — его упрощать нельзя");

// ---------- 3. только замкнутые контуры с заливкой ----------
assert.ok(блок.includes("!f.ring || !st.fill"),
  "упрощается только контур с заливкой: у линии вся суть в обводке");
assert.ok(блок.includes('st.fill === "transparent"'),
  "прозрачная заливка — не заливка, рисовать прямоугольник нечем");

// ---------- 4. порог по ОБЕИМ сторонам ----------
assert.ok(блок.includes("if (!(sw < LOD_PX && sh < LOD_PX)) return false;"),
  "узкая, но длинная зона обязана рисоваться полностью — порог по обеим сторонам");

// ---------- 5. прозрачность заливки сохраняется и не течёт дальше ----------
assert.ok(блок.includes("ctx.globalAlpha = st.fillOpacity"),
  "полупрозрачная зона обязана остаться полупрозрачной и в упрощённом виде");
assert.ok(блок.includes("ctx.globalAlpha = 1"),
  "прозрачность обязана возвращаться, иначе она утечёт на следующие объекты");

// ---------- 6. упрощение вызывается из отрисовки ----------
// Раньше здесь стоял `continue` — тело цикла по объектам жило прямо в drawNow.
// После выноса в drawFeatureOnLayer пропуск объекта выражается через `return`;
// сторожим смысл (нарисовали упрощённо — дальше не идём), а не ключевое слово.
assert.ok(/if \(drawTinyRing\(f, st\)\) (continue|return);/.test(app),
  "после упрощённой отрисовки полная не нужна — иначе объект нарисуется дважды");

console.log("lod-heavy-layers: OK");
