"use strict";

// «Читаемый ЛГР» уезжал в выпуск, а на экране раздувал подпись.
//
// Режим — экранная поблажка: он держит знак разборчивым на любом зуме
// (подпись фиксированного кегля, линия и засечка не тоньше пола) и тем самым
// ЛОМАЕТ масштаб. В коде это сказано прямо, прямо у самой настройки: «лист
// всегда по эталону». Но выключала режим только выгрузка DXF. Лист, альбом и
// печать идут через renderSceneTo, и там режим оставался включённым: подпись
// знака вставала 5 мм на бумаге при ЛЮБОМ масштабе листа вместо положенных
// 10 м местности. На 1:5000 это два с половиной размера.
//
// Вторая половина — экран. У ширины линии и у засечки в читаемом режиме есть
// свой скромный пол (2 px и 7 px), а у подписи не было: она брала эталонный
// кегль «10 м местности», то есть 18.9 px, и держала его на любом зуме. Рядом
// с линией в 1–2 px и интерфейсом в 11 px это и выглядело огромным — с чего
// жалоба и началась.
//
// Замеры после правки: на экране подпись 11 px на всех масштабах от 1:500 до
// 1:5000; на листе — ровно 10 м местности всегда (20 мм при 1:500, 5 мм при
// 1:2000, 2 мм при 1:5000). Во время renderSceneTo режим выключен, после —
// восстановлен.

const assert = require("node:assert/strict");
const { читатьЧистый } = require("./_source");

// ---------- выпуск идёт по эталону ----------
{
  const app = читатьЧистый("app.js");
  const начало = app.indexOf("function renderSceneTo");
  assert.ok(начало > 0, "отрисовка в чужой контекст обязана оставаться находимой");
  const тело = app.slice(начало, app.indexOf("\n}", начало) + 2);
  assert.match(тело, /const savedReadable = state\.lgrReadable;/,
    "прежнее значение режима обязано сохраняться: это настройка человека");
  assert.match(тело, /state\.lgrReadable = false;/,
    "лист, альбом и печать обязаны рисоваться по эталону, а не по экранной поблажке");
  assert.match(тело, /finally \{[\s\S]{0,400}state\.lgrReadable = savedReadable;/,
    "восстанавливать обязано finally: исключение при сборке листа иначе " +
    "оставило бы человека без читаемого режима до перезагрузки");
  const выкл = тело.indexOf("state.lgrReadable = false;");
  const рисуем = тело.indexOf("drawNow()");
  assert.ok(выкл > 0 && выкл < рисуем, "режим выключается ДО отрисовки, а не после");
}

// ---------- на экране у подписи свой пол, как у линии и засечки ----------
{
  const src = читатьЧистый("app-labels-place.js");
  assert.match(src, /const LGR_READABLE_LABEL_PX = \d+;/,
    "у подписи обязан быть свой размер для читаемого режима");
  const размер = Number((src.match(/const LGR_READABLE_LABEL_PX = (\d+);/) || [])[1]);
  const порог = Number((src.match(/const LGR_LABEL_MIN_PX = (\d+)/) || [])[1]);
  assert.ok(размер >= порог,
    `читаемый кегль ${размер} px ниже порога отрисовки ${порог} px — подпись не появится вовсе`);
  assert.ok(размер <= 14,
    `читаемый кегль ${размер} px — это размер бумаги, а не интерфейса; с него и началась жалоба`);
  const функция = src.slice(src.indexOf("function lgrLabelSizePx"));
  const тело = функция.slice(0, функция.indexOf("\n}") + 2);
  assert.match(тело, /if \(lgrReadable\(\)\) return LGR_READABLE_LABEL_PX;/,
    "в читаемом режиме кегль берётся свой, а не эталонный");
  assert.match(тело, /LGR_LABEL_M \* 3779\.5 \/ \(st\.ref_scale \|\| 2000\)/,
    "вне читаемого режима подпись обязана остаться привязанной к местности: 10 м");
}

console.log("lgr-readable-scope: OK");
