"use strict";

// Кадр платит за ВЕРШИНЫ, а не за объекты.
//
// Замер: 200 000 четырёхугольников — 344 мс, 50 000 сорокаугольников — 365 мс.
// Объектов в четыре раза меньше, вершин столько же, цена та же. Отсечение
// невидимого тут не спасает: на полном охвате видно всё. А выгрузки ОСМ и
// портала несут тысячи вершин на прямых участках, и на мелком масштабе
// большинство из них ложится в один и тот же пиксель.
//
// Поэтому перед отрисовкой контур прореживается Дугласом-Пекером — тем же,
// что в окне «Упростить», — но с допуском в ДОЛЮ ПИКСЕЛЯ экрана. Разницы на
// глаз нет по построению: выброшенные вершины отклоняются от хорды меньше,
// чем на 0.6 px.
//
// Замер после: 2000 контуров по 600 вершин (1.2 млн вершин) — 57 мс без
// прореживания против 22 мс с ним, в 2.6 раза. Вблизи контур сохраняет 131
// вершину из 600, то есть ступень подстраивается под зум, а не режет всегда.
//
// Здесь проверяется то, что легко сломать молча: данные, выпуск и файл
// проекта прореживание трогать не имеет права.

const assert = require("node:assert/strict");
const path = require("node:path");
const { читатьЧистый } = require("./_source");

const render = читатьЧистый("app-render.js");
const тело = render.slice(render.indexOf("function lodChain"), render.indexOf("function drawChain"));
assert.ok(тело.length > 0, "прореживание обязано оставаться находимым");

// ---------- выпуск идёт по тем же функциям, и там вершины терять нельзя ----------
assert.match(тело, /if \(_renderTarget\) return chain;/,
  "лист и PDF рисуются тем же кодом: в выпуске чертёж уходит заказчику, " +
  "прореживать его нельзя");

// ---------- допуск в пикселях ЭКРАНА, а не в метрах местности ----------
assert.match(тело, /LOD_ПИКСЕЛЬ \/ state\.view\.k/,
  "допуск обязан пересчитываться из пикселей в метры по текущему зуму, " +
  "иначе на мелком масштабе он ничего не даст, а на крупном срежет видимое");
assert.match(тело, /Math\.pow\(2, Math\.ceil\(Math\.log2\(допуск\)\)\)/,
  "ступень допуска — степень двойки: без неё кэш сбрасывается на каждое движение колеса");

// ---------- кэш не должен попадать в файл проекта ----------
assert.match(тело, /Object\.defineProperty\(chain, "__lod", \{ value: кэш, enumerable: false/,
  "сохранение проекта, снимок истории и выгрузка обходят объект через JSON — " +
  "перечислимое поле уехало бы в файл");

// ---------- дыры прореживаются вместе с внешним контуром ----------
{
  const дыры = render.slice(render.indexOf("function addHoleSubpaths"));
  const конец = дыры.slice(0, дыры.indexOf("\n}") + 2);
  assert.match(конец, /lodChain\(hole, true\)/,
    "если внешнее кольцо упрощено, а дыра нет, они разъезжаются на мелком масштабе");
}

// ---------- схлопнувшийся контур отдаётся исходным, а не пустым ----------
assert.match(тело, /out\.length >= \(close \? 3 : 2\) \? out : chain/,
  "на мелком масштабе контур может схлопнуться: рисовать пустоту нельзя");

// ---------- само прореживание держится в обещанном допуске ----------
{
  global.window = global;
  require(path.join(__dirname, "..", "app-edit.js"));
  const { simplifyChain } = global.GRADO_EDIT;
  // круг с мелкой волной: волна меньше допуска обязана уйти, круг — остаться
  const кольцо = [];
  for (let i = 0; i < 600; i++) {
    const a = 2 * Math.PI * i / 600;
    const r = 150 + 0.2 * Math.sin(a * 40);
    кольцо.push([r * Math.cos(a), r * Math.sin(a)]);
  }
  const допуск = 1.5;
  const out = simplifyChain(кольцо, допуск, true);
  assert.ok(out.length < кольцо.length / 3,
    `прореживание обязано убирать вершины: было ${кольцо.length}, стало ${out.length}`);
  // ни одна выброшенная вершина не отстоит от упрощённого контура дальше допуска
  const расстояние = (p, a, b) => {
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const len = dx * dx + dy * dy;
    let t = len ? ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len : 0;
    t = Math.max(0, Math.min(1, t));
    return Math.hypot(p[0] - (a[0] + dx * t), p[1] - (a[1] + dy * t));
  };
  let худшее = 0;
  for (const p of кольцо) {
    let ближайшее = Infinity;
    for (let i = 0; i < out.length; i++)
      ближайшее = Math.min(ближайшее, расстояние(p, out[i], out[(i + 1) % out.length]));
    худшее = Math.max(худшее, ближайшее);
  }
  assert.ok(худшее <= допуск + 1e-9,
    `выброшенная вершина отстоит от упрощённого контура на ${худшее.toFixed(3)} при допуске ${допуск}`);
}

console.log("render-lod: OK");
