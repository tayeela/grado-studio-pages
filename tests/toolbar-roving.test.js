"use strict";

// Рельс инструментов забирал себе половину клавиатурного пути.
//
// Тридцать три кнопки, каждая — отдельная остановка Tab. Замер до правки:
// 9 остановок из 50 на странице при обычной ширине (18 %), и тем больше, чем
// шире окно. Чтобы добраться с рельса до холста, клавиатурный пользователь
// пробивался через весь набор инструментов.
//
// Паттерн W3C для toolbar ровно об этом: панель целиком получает ОДНУ
// остановку, а внутри ходят стрелками. Ключевое условие — стрелка ДВИГАЕТ
// ФОКУС, но не нажимает кнопку: иначе прогулка по рельсу переключала бы
// инструмент на каждом шаге.
//
// Замер после правки: 1 остановка на рельс, 36 на страницу.

const assert = require("node:assert/strict");
const { читать, читатьЧистый } = require("./_source");

const html = читать("index.html");
const a11y = читатьЧистый("redesign/a11y.js");

// ---------- разметка объявляет себя панелью ----------
{
  const рельс = (html.match(/<nav id="toolbar"[^>]*>/) || [""])[0];
  assert.ok(рельс, "рельс инструментов обязан оставаться находимым");
  assert.match(рельс, /role="toolbar"/,
    "без role=\"toolbar\" ни чтец, ни общий слой доступности не узнают панель");
  assert.match(рельс, /aria-orientation="vertical"/,
    "рельс вертикальный: от этого зависит, какими стрелками по нему ходят");
  assert.match(рельс, /aria-label="[^"]+"/, "у панели обязано быть имя");
}

// ---------- одна остановка на панель, и она не остаётся на спрятанной ----------
{
  assert.match(a11y, /function назначитьОстановку\(bar, цель\) \{[\s\S]{0,200}bar\.querySelectorAll\('button'\)/,
    "остановка снимается со ВСЕХ кнопок панели, включая спрятанные: рельс прячет " +
    "кнопки покинутого режима, и спрятанная уносила остановку с собой");
  assert.match(a11y, /const toolbarItems = bar =>[\s\S]{0,160}\.filter\(visible\)/,
    "остановку получает только ВИДИМАЯ кнопка");
  const ветка = a11y.slice(a11y.indexOf("const bar = document.activeElement"));
  const тело = ветка.slice(0, ветка.indexOf("const menu = document.activeElement"));
  assert.ok(тело.length > 0, "ветка обработки панели обязана оставаться находимой");
  assert.doesNotMatch(тело, /\.click\(\)/,
    "стрелка обязана двигать фокус, а не нажимать кнопку: иначе прогулка по " +
    "рельсу переключает инструмент на каждом шаге");
  assert.match(тело, /Home: 0, End: -1/, "Home и End обязаны прыгать на края панели");
  assert.match(тело, /% items\.length/, "с края фокус обязан переходить на противоположный");
  assert.match(тело, /aria-orientation'\) === 'horizontal'/,
    "направление стрелок берётся из разметки, а не зашивается: панель фильтров слоёв горизонтальная");
}

// ---------- пересчёт не разовый ----------
{
  assert.ok(a11y.indexOf("syncToolbars()") < a11y.lastIndexOf("syncToolbars()"),
    "пересчёт обязан идти не только при запуске: набор видимых кнопок меняется с режимом");
  const наблюдатель = a11y.slice(a11y.indexOf("new MutationObserver"), a11y.indexOf("observer.observe"));
  assert.match(наблюдатель, /syncToolbars\(\);/, "наблюдатель обязан пересчитывать панели");
  const подписка = a11y.slice(a11y.indexOf("observer.observe"), a11y.indexOf("observer.observe") + 260);
  assert.match(подписка, /'data-workspace-mode'/,
    "рельс прячет кнопки одним лишь CSS: без этого признака разметка не меняется " +
    "и пересчёт не запустится");
}

console.log("toolbar-roving: OK");
