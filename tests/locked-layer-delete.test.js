"use strict";

// Замок на слое не защищал от УДАЛЕНИЯ.
//
// Рисовать в закрытый слой addFeature не давал и говорил об этом вслух
// («Слой «X» заблокирован — объект не создан»), а Delete выносил оттуда
// объекты молча: рамкой захватили подложку ЕГРН вместе со своими зонами — и
// она исчезла без единого слова. Замок для того и ставят, чтобы этого не
// случилось.
//
// Замер до правки: два объекта в выборке (один в закрытом слое, один в
// открытом) → удалены ОБА, сообщений ноль.
//
// Замок здесь — предупреждение, а не запрет: решение принимает человек в
// диалоге, а не команда за него. Сторож потому и проверяет не «сколько
// удалено», а то, что РЕШЕНИЕ СПРАШИВАЮТ и по умолчанию ничего не сносят.

const assert = require("node:assert/strict");
const источник = require("./_source").читатьЧистый("app-dialogs.js");

const начало = источник.indexOf("async function deleteSelected() {");
assert.ok(начало > 0,
  "deleteSelected обязана оставаться извлекаемой и асинхронной — она ждёт ответа человека");
const тело = источник.slice(начало, источник.indexOf("\n}", начало) + 2);

// ---- защищённые опознаются ----
assert.match(тело, /layerOf\(f\)\?\.locked/,
  "удаление обязано отличать объекты заблокированных слоёв");
assert.doesNotMatch(тело, /^\s*state\.features = state\.features\.filter\(f => !ids\.has\(f\.id\)\);/m,
  "удалять по исходному набору выбора без вопросов больше нельзя");
assert.match(тело, /state\.features = state\.features\.filter\(f => !кУдалению\.has\(f\.id\)\);/,
  "удаляется ровно тот набор, который подтвердил человек");

// ---- вопрос задаётся, и без ответа ничего не происходит ----
assert.match(тело, /if \(защищены\.length\) \{[\s\S]{0,1200}await ui(Choice|Confirm)\(/,
  "при защищённых объектах в выборке обязан подниматься диалог");
assert.match(тело, /await uiChoice\(/,
  "смешанная выборка: три исхода (остальные / всё / отмена) — это uiChoice, а не confirm");
assert.match(тело, /await uiConfirm\([\s\S]{0,300}danger: true/,
  "выборка целиком из закрытых слоёв: единственное действие необратимо — " +
  "danger-окно, где фокус стоит на «Отмене», а не на удалении");
assert.match(тело, /if \(выбор == null\) return;/,
  "Escape и «Отмена» обязаны означать «ничего не делать»");
assert.match(тело, /if \(!всёравно\) return;/,
  "отказ в danger-окне обязан означать «ничего не делать»");

// ---- названия слоёв в вопросе, а не голое число ----
assert.match(тело, /layerOf\(f\)\?\.title/,
  "человек должен видеть, КАКОЙ слой закрыт, иначе решение принимать не по чему");

// ---- второй Delete поверх открытого окна ----
assert.match(тело, /if \(удалениеСпрашивает\) return;/,
  "модалка перекрывает мышь, но не клавиатуру: повторный Delete не должен " +
  "открывать второе окно поверх первого");
assert.match(источник.slice(0, начало), /let удалениеСпрашивает = false;/,
  "флаг ожидания ответа обязан жить рядом с функцией");
assert.match(тело, /\} finally \{ удалениеСпрашивает = false; \}/,
  "флаг обязан сниматься даже при исключении, иначе Delete умрёт до перезагрузки");

// ---- снимок истории берётся только когда что-то удаляют ----
const снимок = тело.indexOf("snapshot();");
assert.ok(снимок > тело.lastIndexOf("return;"),
  "все выходы «ничего не делаем» обязаны быть ДО snapshot(): отменять нечего");

console.log("locked-layer-delete: OK");
