"use strict";

// Круг выгружался в GeoJSON «бабочкой».
//
// Точки для разбиения брались у featurePts, а он для КРУГА отдаёт ручки
// редактора: центр и четыре стороны света. Кольцо из них самопересекается, и
// площадь выходила 3750 м² вместо 7854 у круга R=50 — занижение почти вдвое,
// молча, в файле, который уходит в чужой САПР. У дуги там же было 8 хорд на
// любой радиус.
//
// Проверяем само разбиение: шаг по УГЛУ, замкнутость, отсутствие центра среди
// вершин и сходимость площади с длиной к точным значениям.

const assert = require("node:assert/strict");
const vm = require("node:vm");

const экспорт = require("./_source").читатьЧистый("app-export.js");
const начало = экспорт.indexOf("const ARC_STEP");
const конец = экспорт.indexOf("function featureGeometry(");
assert.ok(начало > 0 && конец > начало, "разбиение круга и дуги обязано оставаться извлекаемым");

const среда = vm.createContext({ Math });
vm.runInContext(экспорт.slice(начало, конец), среда);
const { circlePoints, arcPoints } = среда;

const площадь = pts => {
  let s = 0;
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i], b = pts[(i + 1) % pts.length];
    s += a[0] * b[1] - b[0] * a[1];
  }
  return Math.abs(s / 2);
};
const длина = pts => {
  let s = 0;
  for (let i = 1; i < pts.length; i++) s += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
  return s;
};

// ---- круг ----
const круг = circlePoints({ cx: 0, cy: 0, r: 50 });
assert.ok(круг.length >= 32, `круг обязан разбиваться минимум на 32 звена, получено ${круг.length}`);
assert.ok(!круг.some(p => p[0] === 0 && p[1] === 0),
  "центр НЕ вершина кольца — именно он и делал из круга бабочку");
for (const p of круг)
  assert.ok(Math.abs(Math.hypot(p[0], p[1]) - 50) < 1e-9, "все вершины лежат на окружности");
const точная = Math.PI * 2500;
assert.ok(Math.abs(площадь(круг) - точная) / точная < 0.002,
  `площадь разбиения ${площадь(круг).toFixed(1)} должна сходиться к ${точная.toFixed(1)}`);
assert.ok(площадь(круг) < точная, "вписанный многоугольник чуть меньше круга — так и должно быть");

// ---- шаг по углу, а не по числу звеньев ----
const малый = circlePoints({ cx: 0, cy: 0, r: 5 });
const большой = circlePoints({ cx: 0, cy: 0, r: 500 });
assert.equal(малый.length, большой.length,
  "шаг задан углом: у круга любого радиуса одинаковое число звеньев");
const стрелка = 500 * (1 - Math.cos(Math.PI / 120));   // прогиб хорды у R=500
assert.ok(стрелка < 0.2, `срез угла у большого круга ${стрелка.toFixed(3)} м — должен быть незаметен`);

// ---- дуга ----
const четверть = arcPoints({ cx: 0, cy: 0, r: 100, a0: 0, sweep: Math.PI / 2 });
assert.ok(Math.abs(длина(четверть) - 100 * Math.PI / 2) < 0.05,
  "длина разбиения дуги сходится к R·sweep");
assert.ok(Math.abs(четверть[0][0] - 100) < 1e-9 && Math.abs(четверть[0][1]) < 1e-9,
  "дуга начинается в точке a0");
assert.ok(Math.abs(четверть[четверть.length - 1][1] - 100) < 1e-9, "и заканчивается на a0+sweep");

const длиннаяДуга = arcPoints({ cx: 0, cy: 0, r: 100, a0: 0, sweep: Math.PI });
assert.ok(длиннаяДуга.length > четверть.length,
  "вдвое больший разворот — вдвое больше звеньев, шаг постоянный");

// ---- вырожденное не роняет выгрузку ----
// сравниваем длину, а не массивы: они рождены в песочнице vm и по прототипу
// не совпадают с массивами этого мира
assert.equal(circlePoints({ cx: 0, cy: 0, r: 0 }).length, 0, "круг нулевого радиуса не даёт вершин");
assert.equal(arcPoints(null).length, 0, "дуги нет — вершин нет");

console.log("export-circle-arc: OK");
