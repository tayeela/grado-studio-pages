"use strict";

// Разбор строки ввода при построении.
//
// Это ядро точного черчения: пока его не было, контур по каталогу координат из
// ГПЗУ или межевого плана начертить было нельзя — только мышью по привязкам,
// приблизительно. Поэтому проверяем не «работает ли», а ЧИСЛА: длина обязана
// быть той, что набрана, до миллиметра.

const assert = require("node:assert/strict");
const { parseInputLine, describeInputLine } = require("../app-input-line.js");

const близко = (a, b, ε, что) => assert.ok(Math.abs(a - b) < ε,
  `${что}: ожидалось ${b}, получено ${a}`);

// ---------- длина по направлению курсора ----------
{
  const p = parseInputLine("25", { last: [0, 0], cursor: [10, 0] });
  близко(p.x, 25, 1e-9, "длина на восток");
  близко(p.y, 0, 1e-9, "длина на восток, север");

  // направление берётся у курсора, а длина — набранная
  const d = parseInputLine("25", { last: [0, 0], cursor: [3, 4] });   // 3-4-5
  близко(Math.hypot(d.x, d.y), 25, 1e-9, "длина по косому направлению");
  близко(d.x, 15, 1e-9, "восточная составляющая");
  близко(d.y, 20, 1e-9, "северная составляющая");

  // курсор в той же точке — направления нет, точку ставить не из чего
  assert.equal(parseInputLine("25", { last: [5, 5], cursor: [5, 5] }), null,
    "без направления длина бессмысленна");
}

// ---------- полярный ввод: длина<угол ----------
{
  const п = parseInputLine("25<90", { last: [0, 0] });
  близко(п.x, 0, 1e-9, "25<90 — строго на север, восточная");
  близко(п.y, 25, 1e-9, "25<90 — строго на север, северная");

  const в = parseInputLine("25<0", { last: [10, 10] });
  близко(в.x, 35, 1e-9, "0° — на восток");
  близко(в.y, 10, 1e-9, "0° — на восток, север не меняется");

  const косой = parseInputLine("100<45", { last: [0, 0] });
  близко(косой.x, 70.71067811, 1e-6, "45° восточная");
  близко(косой.y, 70.71067811, 1e-6, "45° северная");

  // без последней точки полярный ввод не от чего откладывать
  assert.equal(parseInputLine("25<90", { last: null }), null, "полярный ввод без начала");
}

// ---------- приращение и абсолютная точка ----------
{
  const о = parseInputLine("@25,10", { last: [100, 200] });
  близко(о.x, 125, 1e-9, "приращение по востоку");
  близко(о.y, 210, 1e-9, "приращение по северу");

  const а = parseInputLine("1000,2000", { last: [1, 1] });
  близко(а.x, 1000, 1e-9, "абсолютная точка, восток");
  близко(а.y, 2000, 1e-9, "абсолютная точка, север");
  assert.equal(а.kind, "абсолютная", "пара без @ — абсолютная, как в CAD");
}

// ---------- геодезический порядок: X север, Y восток ----------
{
  // Ловушка, на которой ломаются переносы: в МСК-77 X это СЕВЕР, а на холсте
  // x — восток. Перепутав, получаешь контур, повёрнутый на 90°.
  const г = parseInputLine("X=12345.67 Y=8901.23", {});
  близко(г.x, 8901.23, 1e-9, "Y (восток) обязан лечь в x холста");
  близко(г.y, 12345.67, 1e-9, "X (север) обязан лечь в y холста");
  assert.equal(г.kind, "геодезическая");

  // порядок записи не важен — важны сами буквы
  const обратно = parseInputLine("Y=8901.23 X=12345.67", {});
  assert.deepEqual([обратно.x, обратно.y], [8901.23, 12345.67],
    "порядок записи не меняет, что север это X");

  // строчные и разделители
  const мелкими = parseInputLine("x=100, y=200", {});
  assert.deepEqual([мелкими.x, мелкими.y], [200, 100], "строчные буквы и запятая");

  // половина набрана — точку ставить рано
  assert.equal(parseInputLine("X=12345.67", {}), null, "одна координата — не точка");
}

// ---------- десятичная точка, а не запятая ----------
{
  // Запятая — разделитель координат, как в CAD. Иначе «25,5» было бы двузначно:
  // и «двадцать пять с половиной», и пара (25; 5).
  const пара = parseInputLine("25,5", { last: [0, 0] });
  assert.equal(пара.kind, "абсолютная", "запятая — разделитель, не десятичная");
  const дробная = parseInputLine("25.5", { last: [0, 0], cursor: [1, 0] });
  близко(дробная.x, 25.5, 1e-9, "точка — десятичный разделитель");
}

// ---------- прежние привычки не сломаны ----------
{
  // До этого разбора вершину набирали как «100 200» или «100;200» — пробел и
  // точка с запятой обязаны работать по-прежнему, иначе правка ломает руки.
  const пробел = parseInputLine("100 200", {});
  assert.deepEqual([пробел.x, пробел.y], [100, 200], "пробел как разделитель");
  const точкаЗапятая = parseInputLine("100;200", {});
  assert.deepEqual([точкаЗапятая.x, точкаЗапятая.y], [100, 200], "точка с запятой");
}

// ---------- мусор не создаёт точку ----------
{
  for (const плохо of ["", "   ", "abc", "<90", "@", ",", "25<", "x=", "25<abc"])
    assert.equal(parseInputLine(плохо, { last: [0, 0], cursor: [1, 1] }), null,
      `«${плохо}» не должно превращаться в точку`);
}

// ---------- подсказка объясняет, как понята строка ----------
{
  assert.match(describeInputLine("25<90", { last: [0, 0] }), /полярная: 0\.00 \/ 25\.00/,
    "подсказка показывает разобранную точку");
  assert.match(describeInputLine("X=1", {}), /X= север, Y= восток/,
    "недобранная геодезическая пара объясняет порядок осей");
  assert.match(describeInputLine("", {}), /длина.*угол.*приращение/,
    "пустая строка перечисляет формы ввода");
}

console.log("coord-input: OK");
